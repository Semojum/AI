    return {
        "backend": backend,
        "model": os.getenv("CAPTION_MODEL", "claude-sonnet-5") if backend == "anthropic" else "gpt-4o",
        "key_env": "ANTHROPIC_API_KEY" if backend == "anthropic" else "OPENAI_API_KEY",
        "key_present": bool((key or "").strip()),
    }


