# MinerU가 잘라 주는 크롭은 작다 — dev 331장 실측 중앙값 334×214px, 86%가 한 변 300px 미만.
# 크롭이 작을수록 캡션이 틀린다(짧은 변 ≤146px 42.7% vs ≥312px 28.2%, 2026-08-10 실측).
# 확대해도 화소 정보는 안 늘지만 비전 인코더가 같은 내용에 더 많은 패치를 쓴다.
# `CAPTION_UPSCALE=3`처럼 배율을 줄 때만 동작한다(기본 꺼짐 — 운영 동작 불변).
_MAX_EDGE = 1568   # 이보다 크면 서버가 되레 줄이고 토큰만 더 든다


def _maybe_upscale(raw: bytes) -> bytes:
    try:
        f = float(os.getenv("CAPTION_UPSCALE", "") or 0)
    except ValueError:
        return raw
    if f <= 1:
        return raw
    try:
        from io import BytesIO

        from PIL import Image
        im = Image.open(BytesIO(raw))
        f = min(f, _MAX_EDGE / max(im.size))
        if f <= 1:
            return raw
        buf = BytesIO()
        im.resize((round(im.width * f), round(im.height * f)), Image.LANCZOS).save(
            buf, format=im.format or "JPEG", quality=95)
        return buf.getvalue()
    except Exception:  # noqa: BLE001 — 확대는 있으면 좋은 것, 실패하면 원본으로 간다
        return raw


# 백엔드 전환 — CAPTION_BACKEND로 고른다(기본 anthropic). 모델은 CAPTION_MODEL.
#   예: CAPTION_BACKEND=openai CAPTION_MODEL=gpt-4o
def _caption_anthropic(b64: str, mime: str, prompt: str, tail: str = "") -> str:
    import anthropic
    from app.core.limits import estimate_tokens, llm_limiter
    from app.utils.req_log import record_anthropic
    # 계정 분당 상한(요청·토큰). 동시 연결은 이미 caption_slot이 조인다.
    # b64는 원본의 4/3배라 실제 바이트로 환산해 넘긴다.
    # 재료 블록을 켜면 출력이 설명 + 관측 목록이라 500으로는 잘린다(값이 사라지는 것이
    # 한 줄로 붙는 것보다 나쁘다). 꺼져 있으면 종전 그대로 500 — 운영 동작 불변.
    out_cap = 1200 if _material_on() else 500
    llm_limiter().acquire_sync(estimate_tokens(prompt + tail, len(b64) * 3 // 4), out_cap)
    model = os.getenv("CAPTION_MODEL", "claude-sonnet-5")
    client = anthropic.Anthropic(api_key=config.anthropic_api_key or None, timeout=60.0, max_retries=1)  # 행 방지(2026-07-19 스톨 실측)
    # ★ thinking을 꺼야 한다(2026-08-08 QA 16번 실측). claude-sonnet-5는 `thinking`을 안 주면
    #   **적응형 사고가 기본**이고, max_tokens는 사고+본문 합계 상한이라 복잡한 그림에서
    #   500토큰을 사고가 다 먹고 캡션이 **빈 문자열**로 돌아온다
    #   (예3-50 순서도: stop_reason=max_tokens, thinking_tokens=499, text 블록 0개).
    #   규정 정답 22건 중 3건(14%)이 이 경로로 빈 캡션이었다. 캡셔닝은 묘사 과제라
    #   사고가 품질을 올리지 않는다 — 끄는 쪽이 정확하고 싸다.
    # ★ 프롬프트는 `system`에 둔다 — 프롬프트 캐싱(2026-08-23, 대표 지시 API비용 2번).
    #   캐시는 **접두 일치**이고 요청은 `tools → system → messages` 순으로 렌더된다.
    #   프롬프트가 사용자 턴에서 이미지 **뒤**에 있으면 접두에 매번 다른 이미지가 끼어
    #   적중률이 구조적으로 0이다. 캡션 프롬프트는 유형별로 고정이고 1,784~3,041자
    #   (= 최소 캐시 길이 1,024토큰을 넘는다)라, system으로 올리면 4종 모두 캐시에 얹힌다.
    #   적중은 `usage.cache_read_input_tokens`로 확인한다 — req_log가 집계해 보고한다.
    # ★★ 그런데 **경계 자리가 틀려 있었다**(2026-09-08 감사 1번, #760). 요소마다 다른
    #   이웃 본문(`_context_block`)을 같은 블록 **안**에 이어 붙여 `cache_control` 을 그
    #   끝에 걸었다 — 접두가 매번 달라져 적중이 구조적으로 0이다. 실측 8호출에
    #   `cache_read=0 · cache_write=52,620`. 쓰기는 정가의 1.25배라, 못 읽는 캐시는
    #   **캐싱을 아예 안 쓰는 것보다 25% 비싸다.**
    #   그래서 `system` 을 둘로 가른다 — 유형별 고정 프롬프트만 첫 블록(캐시 경계)이고,
    #   이웃 본문·재료 블록은 경계 **뒤** 두 번째 블록이다. 이어 붙인 글자는 종전과
    #   한 글자도 다르지 않다(`prompt + tail` = 옛 `prompt`). 그래서 캐시 판 번호는
    #   안 올린다 — 번호는 **문안이 바뀔 때** 올리는 것이고, 여기는 블록 경계만 옮겼다.
    # ★ temperature 는 넣지 마라 — claude-sonnet-5 는 이 인자를 거절한다(2026-09-08 실측,
    #   400 `temperature` is deprecated for this model). 캡션 온도를 0 으로 낮추자는 요청이
    #   와도 이 경로엔 손댈 자리가 없다. 회차간 흔들림(같은 설정 2회: 사실 141↔146개·
    #   줄 수 95↔104)은 모델 고정 샘플링에서 오는 것이라 인자로 못 줄인다.
    system = [{"type": "text", "text": prompt,
               "cache_control": {"type": "ephemeral"}}]
    if tail:
        system.append({"type": "text", "text": tail})
    resp = client.messages.create(
        model=model,
        max_tokens=out_cap,
        thinking={"type": "disabled"},
        system=system,
        messages=[{
            "role": "user",
            "content": [
                {"type": "image",
                 "source": {"type": "base64", "media_type": mime, "data": b64}},
            ],
        }],
    )
    # 실토큰을 요청 집계로 흘린다 — 근사치 1500/500을 곱하던 자리(2026-08-13).
    record_anthropic("캡셔닝", model, getattr(resp, "usage", None))
    _record_usage(resp)               # 프로세스 전역 누계(오프라인 배치 비용 보고용)
    return "".join(b.text for b in resp.content if b.type == "text").strip()


_USAGE = {"calls": 0, "in": 0, "out": 0, "cache_read": 0, "cache_write": 0}


def _record_usage(resp) -> None:
    # 캐시 토큰도 센다 — 프롬프트 캐싱을 켠 뒤로 `in` 만 보면 실제로 오간 토큰이
    # 안 보인다(적중분은 `input_tokens` 에 안 실린다). 오프라인 배치 보고용.
    u = getattr(resp, "usage", None)
    if not u:
        return
    _USAGE["calls"] += 1
    _USAGE["in"] += getattr(u, "input_tokens", 0) or 0
    _USAGE["out"] += getattr(u, "output_tokens", 0) or 0
    _USAGE["cache_read"] += getattr(u, "cache_read_input_tokens", 0) or 0
    _USAGE["cache_write"] += getattr(u, "cache_creation_input_tokens", 0) or 0


def usage_report() -> dict:
    """이번 프로세스의 캡셔닝 API 사용량(호출·토큰). 비용 보고용."""
    return dict(_USAGE)


# 유형 제시어(§6.3.4(1)): 캡션 첫머리를 자료 유형으로 시작한다. LLM 프롬프트가 아니라
# rule-based로 붙인다 — 분류기가 유형을 이미 알고, 규정 틀 검증(kpi_regulation.py)에서
# LLM이 제시어를 자주 빼먹는 게 최대 실패 항목이었다(2026-07-17, 틀 통과 8/18의 주원인).
_TYPE_WORD = {"image": "그림", "cartoon": "만화", "chart": "그래프", "chart_graph": "그래프",
              "diagram": "그림"}
_TYPE_WORDS_ALL = ("그림", "사진", "그래프", "삽화", "만화", "지도", "표", "도표")


_TYPE_COLON_RES = None  # lazy — 유형 제시어+쌍점 패턴


def _has_type_colon(s: str) -> bool:
    """유형 제시어(그림·그래프 등)+쌍점으로 시작하는가 — 지침 §6.3.4 '유형, 쌍점, 내용'."""
    global _TYPE_COLON_RES
    if _TYPE_COLON_RES is None:
        _TYPE_COLON_RES = re.compile(
            r"^(?:" + "|".join(map(re.escape, _TYPE_WORDS_ALL)) + r")\s*[:：]")
    return bool(_TYPE_COLON_RES.match(s))


# 제목줄 패턴: 유형+번호("그림 2-1." "표 1.") — 제시어가 아니라 자료 제목이다(지침 예3-20).
_TITLE_LINE_RE = re.compile(
    r"^(?:" + "|".join(map(re.escape, _TYPE_WORDS_ALL)) + r")\s*\d+(?:[.\-]\d+)*\.?\s")


def _ensure_type_word(text: str, image_type: str) -> str:
    """지침 §6.3.4: 설명 본문은 '유형 제시어 + 쌍점'으로 시작해야 한다.

    ⚠ 단순 startswith(유형) 판정은 제목줄("그림 2-1. …")을 제시어로 오판해 본문
    제시어를 생략시켰다(지침 예3-20 프레임 검사 실측, 2026-07-19). 쌍점까지 요구하고,
    제목줄이면 제목은 유지한 채 다음 본문 앞에 제시어를 삽입한다.
    """
    t = (text or "").strip()
    if not t:
        return t
    if _has_type_colon(t):
        return t
    tw = _TYPE_WORD.get(image_type, "그림")
    if _TITLE_LINE_RE.match(t):
        nl = t.find("\n")
        if nl > 0:
            title, body = t[:nl].rstrip(), t[nl + 1:].strip()
            if body and not _has_type_colon(body):
                return f"{title}\n{tw}: {body}"
            return t
        return t  # 제목 한 줄뿐 — 본문 없음, 그대로
    return f"{tw}: {t}"


