# 제목줄 패턴: 유형+번호("그림 2-1." "표 1.") — 제시어가 아니라 자료 제목이다(지침 예3-20).
_TITLE_LINE_RE = re.compile(
    r"^(?:" + "|".join(map(re.escape, _TYPE_WORDS_ALL)) + r")\s*\d+(?:[.\-]\d+)*\.?\s")


def _ensure_type_word(text: str, image_type: str) -> str:
    """지침 §6.3.4: 설명 본문은 '유형 제시어 + 쌍점'으로 시작해야 한다.

    ⚠ 단순 startswith(유형) 판정은 제목줄("그림 2-1. …")을 제시어로 오판해 본문
    제시어를 생략시켰다(지침 예3-20 프레임 검사 실측, 2026-07-19). 쌍점까지 요구하고,
    제목줄이면 제목은 유지한 채 다음 본문 앞에 제시어를 삽입한다.
    """
    t = (text or "").strip()
    if not t:
        return t
    if _has_type_colon(t):
        return t
    tw = _TYPE_WORD.get(image_type, "그림")
    if _TITLE_LINE_RE.match(t):
        nl = t.find("\n")
        if nl > 0:
            title, body = t[:nl].rstrip(), t[nl + 1:].strip()
            if body and not _has_type_colon(body):
                return f"{title}\n{tw}: {body}"
            return t
        return t  # 제목 한 줄뿐 — 본문 없음, 그대로
    return f"{tw}: {t}"


# ★ 메타 응답 차단(2026-08-10 실측). 이미지를 분명히 보냈는데도 모델이 "이미지가 첨부되지
#   않았습니다. 파일을 첨부해 주시면 …"이라고 되묻는 응답이 dev 371건 중 5건(1.3%) 나왔고,
#   그대로 캡션으로 저장돼 점역자 주로 나갔다. 시각장애 학생이 손으로 읽는 자리에
#   "파일을 첨부해 주세요"가 찍히는 것이라 빈 캡션보다 나쁘다.
#   빈 응답과 같은 취급(= 빈 문자열 → CAPTION_FAILED)으로 돌린다. 결정적 방어라 비용 0.
#   dev 371건 대조: 적중 5/5, 오탐 0('제공/없/첨부'가 든 정상 캡션 20건은 통과).
# 2026-08-10 보강 — 요청 문구가 없는 **맨 거부**("이미지를 볼 수 없습니다")가 위 패턴을
#   빠져나갔다. dev 실제 캡션 371건에 넓힌 식을 걸어 **적중은 그대로 5건, 오탐 0**을 확인했다.
_META_RE = re.compile(
    r"(첨부|제공|업로드)(되지|해|하지)\s*않|이미지가\s*(없|첨부|제공)|"
    r"주시면|드리겠습니다|드릴게요|알려\s*주세요|보내\s*주세요|"
    r"(이미지|그림|사진)(을|를)?\s*(볼|확인할|읽을)\s*수\s*없|"
    r"^죄송|도와\s*드릴|무엇을\s*도와")


def _reject_meta(text: str) -> str:
    """그림 대신 사용자에게 말을 거는 응답이면 실패로 돌린다."""
    return "" if _META_RE.search(text or "") else text



# ── 열거 항목은 줄을 나눈다 (2026-08-12 대표 지시) ──────────────────────────
# 캡셔너는 여러 정보를 **한 줄에 쭉** 이어 쓰는 버릇이 있다:
#   "1. 광개토대왕릉비의 모습이다 2. 장수왕비의 모습이다"
# 점역사 편집창에서 이걸 읽으려면 눈으로 번호를 찾아 끊어야 한다. 항목 앞에서 줄을 나눈다.
#
# 줄을 나누는 게 점자에도 이롭다 — `visual_drafts`의 개조식(2안)은 **줄 단위로** 항목을
# 만들기 때문에(`_outline_item`), 한 줄로 뭉친 캡션은 개조식이 되어도 항목이 하나뿐이다.
# 여기서 나눠 주면 개조식이 실제로 개조식이 된다.
#
# ⚠ 점자 출력의 줄 수가 늘지는 않는다. 점역자 주 한 덩이는 논리 줄 하나라
#   `visual_drafts._oneline`이 다시 접는다(§6.3.4(1)). 나눈 줄이 쓰이는 곳은
#   개조식 항목화와 사람이 읽는 편집창이다.
_ENUM_SPLIT_RE = re.compile(
    r"(?<=[^\s])\s+(?="                     # 앞에 글자가 있고, 뒤가 항목 머리일 때만
    r"\d{1,2}\s*[.)]\s|"                    # 1. 2) …
    r"[①-⑳㉑-㉟]|"                            # ①②③ …
    r"[가-힣]\s*[.)]\s|"                     # 가. 나) …
    r"[-·•]\s"                               # - · •
    r")")
# 문장 끝 마침표는 숫자 항목과 구분이 어렵다 — 소수점·연도는 안 쪼갠다.
_DECIMAL_RE = re.compile(r"\d\s*[.]\s*\d")


# '(상황)'·'상황:' 말머리 — 프롬프트로 막아도 모델이 붙이는 일이 있어 후처리로도 걷는다.
# 지침 예5-4·5-5는 '만화:' 뒤에 말머리 없이 바로 문장이 온다.
_SITUATION_HEAD_RE = re.compile(
    r"(?m)(^|^\s*\S{1,4}\s*[:：]\s*)"      # 줄머리, 또는 '만화:' 같은 유형 제시어 뒤
    r"[(（\[【]?\s*상황(?![가-힣])\s*[)）\]】]?\s*[:：]?\s*")


def _strip_situation_head(text: str) -> str:
    """줄머리의 '(상황)'·'상황:' 말머리를 뗀다. 문장 자체는 남긴다."""
    return _SITUATION_HEAD_RE.sub(lambda m: m.group(1), text or "")


def _split_enumerations(text: str) -> str:
    """한 줄에 이어 쓴 열거 항목 사이에 줄바꿈을 넣는다."""
    out = []
    for line in (text or "").splitlines():
        if len(line) < 20 or _DECIMAL_RE.search(line):
            out.append(line)
            continue
        out.append(_ENUM_SPLIT_RE.sub("\n", line))
    lines = "\n".join(out).splitlines()
    # 유형 제시어만 홀로 남는 줄("그림:")은 다음 항목에 붙인다 — §6.3.4(1)은 유형과 설명을
    # 한 덩이로 본다. 편집창에서도 콜론 하나짜리 줄은 읽는 데 방해만 된다.
    if len(lines) > 1 and lines[0].rstrip().endswith((":", "：")):
        lines[:2] = [f"{lines[0].rstrip()} {lines[1].lstrip()}"]
    return "\n".join(lines)


def _cache_file(raw: bytes, image_type: str, prompt: str) -> Path | None:
    """★ A/B 판정용 캡션 캐시(2026-08-08). `CAPTION_CACHE_DIR`를 줄 때만 동작한다.

    캡셔닝 LLM은 같은 그림에 매번 다른 캡션을 준다(실측 12/12 상이). 그런데
    `claude-sonnet-5`는 `temperature`를 거부하므로(400) 파라미터로 결정성을 살 수 없다.
    한편 MinerU가 잘라내는 크롭 이미지는 실행 간 **바이트 동일**하다(실측 285장/94쪽
    전량 일치). 그래서 이미지 내용 해시로 캡션을 재사용하면 반복 실행이 결정적이 된다.
    같은 라운드를 두 번 돌려 비교할 때 캡션을 고정하고 점역 변경만 보게 하는 장치다.
    운영 기본값은 꺼짐(환경변수 없음) — 운영 동작은 바뀌지 않는다.
    """
    d = os.getenv("CAPTION_CACHE_DIR")
    if not d:
        return None
    key = hashlib.sha256(
        b"|".join([raw, image_type.encode(),
                   os.getenv("CAPTION_BACKEND", "anthropic").encode(),
                   os.getenv("CAPTION_MODEL", "claude-sonnet-5").encode(),
                   prompt.encode()])
    ).hexdigest()
    p = Path(d)
    p.mkdir(parents=True, exist_ok=True)
    return p / f"{key}.txt"


def caption(image_path: str, image_type: str = "image") -> str:
    """
    image_type: 'image' | 'cartoon' | 'chart'
    Returns Korean description string.
    """
    prompt = _PROMPTS.get(image_type, _PROMPTS["image"])

    with open(image_path, "rb") as f:
        raw = _maybe_upscale(f.read())   # 캐시 키도 확대본 기준 — 배율이 다르면 캐시가 갈린다
    b64 = base64.b64encode(raw).decode()

    cache = _cache_file(raw, image_type, prompt)
    if cache is not None and cache.exists():
        return cache.read_text(encoding="utf-8")

    ext = Path(image_path).suffix.lstrip(".").lower()
    mime = "image/jpeg" if ext in ("jpg", "jpeg") else f"image/{ext}"

    if os.getenv("CAPTION_BACKEND", "anthropic") == "anthropic":
        text = _split_enumerations(_strip_situation_head(
            _ensure_type_word(_reject_meta(_caption_anthropic(b64, mime, prompt)), image_type)))
        # 빈 응답은 캐시하지 않는다 — 한 번 비면 재실행이 영구히 빈 캡션을 재생한다.
        if cache is not None and text.strip():
            cache.write_text(text, encoding="utf-8")
        return text

    from app.utils.req_log import inc_gpt4o
    inc_gpt4o()
    resp = _get_client().chat.completions.create(
        model="gpt-4o",
        messages=[
            {
                "role": "user",
                "content": [
                    {"type": "image_url", "image_url": {"url": f"data:{mime};base64,{b64}"}},
                    {"type": "text", "text": prompt},
                ],
            }
        ],
        max_tokens=500,
        temperature=0.3,
    )
    text = _ensure_type_word(_reject_meta(resp.choices[0].message.content.strip()), image_type)
    if cache is not None and text.strip():
        cache.write_text(text, encoding="utf-8")
    return text
