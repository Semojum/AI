#   빠져나갔다. dev 실제 캡션 371건에 넓힌 식을 걸어 **적중은 그대로 5건, 오탐 0**을 확인했다.
# 2026-08-15 보강(eval 세션 이관 건) — **판독 불능 표명**이 위 식을 빠져나갔다.
#   실제 미검출 응답: "이미지의 해상도가 낮아 점자 패턴을 정확히 **판독할** 수 없습니다.
