# ★ 수식 경로는 무관하다: _apply_book_style은 _translate_with_braillify가 <!수식> 태그로
#   쪼갠 **텍스트 세그먼트에만** 걸리고(_FORMULA_RE.split의 짝수 인덱스), 수식 세그먼트는
