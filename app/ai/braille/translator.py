#   ⠷⠄…⠠⠾라 문장부호 대괄호와 다른 체계다(실측: <!수식>[3,5]<!/수식> → ⠷⠄⠼⠉⠂⠑⠠⠾).
#
# ⚠ 아래 관행 분기는 기본값에서 **꺼져 있다**. 정답 코퍼스(2012 EBS 수능특강 점역본)는
