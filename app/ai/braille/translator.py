_ROMAN_CELL = {**_ROMAN_CELL_UPPER, **_ROMAN_CELL_LOWER}
_ROMAN_CELL_RE = re.compile("[" + "".join(_ROMAN_CELL) + "]")


# ★ 2026-08-27 — **섹션번호 자리로 좁힌다.** 위 관행 근거는 섹션번호(Ⅱ. Ⅲ. …) 실측
#   세 쪽뿐인데(frozen 사회문화 p046·154, 세계사 p016) 코드는 수식 밖 로마숫자 **전부**에
