def _border_line(name: str, title_braille: str) -> str:
    """글상자/표 테두리 32칸 줄. 제목 있으면 BBPG-1.2.5(4)② 배치(7칸, 양옆 띔)."""
    cap, fill = _BORDER_FILL[name]
