    #   "사회문화 p030 실측 '--.ul'"이었는데 그 실측이 **구판**이다. 신규 gold는 반대다:
    #   묵자 줄머리 하이픈 dev 119·val 99에 대해 **gold는 한 칸 붙임표+공백을
