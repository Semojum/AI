def table_split(n: int) -> str:
    """표를 여러 개로 쪼갰을 때 (도서지침 예3-17)."""
    return f"가독성을 고려하여 {n}개의 표로 분할 점역함"


def indent_hierarchy(step: int = 2, what: str = "항목") -> str:
    """위계를 들여쓰기로 나타냈을 때 (자료지침 예6-22).

    점자에는 선·상자가 없으니 위계가 들여쓰기로만 남는다. 몇 칸이 한 단계인지 말해
    주지 않으면 독자는 빈칸을 세도 단계를 못 센다.

    `what`은 무엇의 위계인지 — 정본 예6-22는 조직도라 "기구"라 쓴다. 일반 시각자료
    개조식에는 "항목"이 맞다. 조직도 말을 그림에 그대로 쓰면 없는 조직을 있다고 읽힌다.
    """
    return f"하위에 속한 {what}{_eul(what)} {step}칸씩 들여 쓰기함"


# ── B. 생략 고지 ─────────────────────────────────────────────────────────────
def omitted(what: str, reason: str = "") -> str:
    """무엇을 왜 뺐는지 (자료지침 예6-15 · 도서지침 예1-15)."""
    return f"{reason} {what}을 생략함".strip() if reason else f"{what} 생략"


# ── D. 읽는 순서 안내 ────────────────────────────────────────────────────────
def reading_order(parts: list[str]) -> str:
    """여러 갈래를 어떤 순서로 폈는지 (자료지침 예7-18)."""
    return ", ".join(parts) + " 순으로 점역하였음"


def layout_scan(where: str = "상단") -> str:
    """화면·지면을 어느 쪽부터 훑었는지 (자료지침 예6-24)."""
    return f"{where}부터 영역별 표기함"


# ── G. 장면 표지 ─────────────────────────────────────────────────────────────
def scene(n: int) -> str:
    """만화 장면 표지 (자료지침 예5-5)."""
    return f"장면 {n}"
