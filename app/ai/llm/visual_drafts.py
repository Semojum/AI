# 그래서 **가늠자를 씻어서** 비교한다. 시연 12쪽에서 2줄이 지워지고 오탐은 0이었다.
# ⚠ 제목·유형 줄하고만 견준다. 앞선 항목 전부와 견주면 위계가 반복되는 정상 항목을 지운다.
_GIST_STRIP = re.compile(r"[\s$·,.…‘’“”\"'()\[\]{}~\-–—:;/]")
# 되풀이 판정에 쓰는 닮음 문턱. 이 값 아래는 서로 다른 말로 본다.
#   0.80 은 gold 대조에서 정한 값 — "아메바 현미경 사진 - 단세포 생물 예시" 와
#   "아메바 현미경 사진, 단세포 생물의 예시임." 같은 조사·구분자 차이만 잡고,
#   "가로축: 시간" 과 "세로축: 농도" 처럼 뼈대만 같은 줄은 안 잡는다.
#   ★ 0.80 으로 뒀다가 "5월 ○○군 풍혈지: 12.0" 과 "7월 ○○군 풍혈지: 14.2" 가 같은 말로
#     잡혔다. 값이 다른 자료 줄을 지우면 정보가 사라진다 — 문턱을 올리고 숫자 가드를 뒀다.
_GIST_RATIO = 0.88
_GIST_MIN_LEN = 8        # 짧은 말은 우연히 닮는다
_DIGITS = re.compile(r"\d+")


def _gist(s: str) -> str:
    return _GIST_STRIP.sub("", s or "")


_TYPE_HEAD_RE = re.compile(
    r"^\s*(그림|사진|그래프|만화|지도|도표|삽화|영상|모식도|개념도|흐름도|구조도|"
    r"조직도|가계도|연대표|계통도|순서도)\s*[::,]\s*")


def _strip_type_word(s: str) -> str:
    """머리줄에서 제시어를 뗀다 — `그림: 퍼킨스 점자 타자기` → `퍼킨스 점자 타자기`."""
    return _TYPE_HEAD_RE.sub("", s or "").strip()


def _same_gist(a: str, b: str) -> bool:
    """두 줄이 사실상 같은 문구인가 — 구분자·공백·문장부호 차이는 무시한다.

    완전 포함만 보던 때는 어순이나 조사가 조금만 달라도 못 잡았다. 실측에서
    "검색과 메뉴 아이콘" 과 "검색 아이콘과 메뉴 아이콘 두 개로 구성" 이 둘 다 남아
    같은 말을 두 번 적었다. 여덟 자 이상이면 닮음도 함께 본다.
    """
    na, nb = _gist(a), _gist(b)
    if not (na and nb):
        return False
    if na == nb:
        return True
    # ★ 포함은 **길이가 엇비슷할 때만** 같은 말로 본다(2026-09-07).
    #   짧은 쪽이 긴 쪽에 들어 있다는 것만으로 지우면 **묶음 머리줄이 사라진다.**
    #   실측(캡션 1,811건 재생): `중국 국민당군과 중국 공산당군의 병력 변화` 가 머리줄일 때
    #   계열 머리 `중국 국민당군`·`중국 공산당군` 두 줄이 지워져, 값 여덟 줄이 어느 계열
    #   것인지 알 수 없게 됐다. 머리줄이 `그래프` 한 낱말이면 '그래프'가 든 항목이 통째로
    #   날아가기도 했다(`가로축은 연령대 … 나타낸 그래프이다.`).
    #   0.7 은 이 필터가 원래 잡던 얼굴(제목을 그대로 되풀이한 항목, 길이비 ~1.0)은 그대로
    #   잡고 묶음 머리줄(길이비 0.35~0.45)은 놓아 준다.
    if na in nb or nb in na:
        return min(len(na), len(nb)) / max(len(na), len(nb)) >= 0.7
    if min(len(na), len(nb)) < _GIST_MIN_LEN:
        return False
    # 숫자가 다르면 값이 다른 자료 줄이다 — 닮았어도 지우지 않는다.
    if _DIGITS.findall(na) != _DIGITS.findall(nb):
        return False
    return SequenceMatcher(None, na, nb).ratio() >= _GIST_RATIO


def _dup_of_body(text: str, body_texts: list[str] | None) -> bool:
    """이 전사 항목이 **같은 그림 안 본문 텍스트**에 이미 통째로 들어 있나(원장 C-78 · F23).

    지우는 쪽은 **설명**이다. gold 는 그림 안 글자를 **본문에 한 번만** 적는다
    (자리 실측: 본문 27 : 설명 1). 우리는 본문 요소로 한 번 + 설명에 또 한 번 = 두 번 적었다.

    규칙을 좁게 잡는다 — 넓히면 **본문에 있어야 할 것까지 지운다**:
      · **8자 이상**만 본다(`_DEDUP_MIN_LEN`). 짧은 말은 우연히 겹친다(`(가)`·`X 주사`).
      · **정규화 후 완전 포함**일 때만(공백·태그 제거).
      · **줄 단위**로만 지운다. 문장 중간을 잘라내면 "A와 B를 잇는 화살표"에서 A만 빠져
        문장이 깨진다(원장 C-78 경고).
    실측 대상은 **42건**(8자 이상 중복). 본문에만 있는 **224건은 설명에 없으므로 안 닿는다.**
    """
    if not body_texts:
        return False
    n = _norm_for_dedup(text)
    if len(n) < _DEDUP_MIN_LEN:
        return False
    # ★ 본문 쪽도 여기서 다시 정규화한다. `_mark_body_texts_in_visuals` 가 이미 해서 오지만,
    #   호출자가 원문을 그대로 주면 **조용히 아무것도 안 지운다**(공백 하나에 포함이 깨진다).
    #   말없이 꺼지는 규칙이 제일 나쁘다 — 방어적으로 양쪽 다 정규화한다.
    return any(n in _norm_for_dedup(b) for b in body_texts)


def _outline_text_indents(
    label: str, title: str, desc: str, items: list[tuple[int, str]], kind: str = "",
    body_texts: list[str] | None = None,
) -> tuple[str, list[int]]:
    """개조식 → (텍스트, 줄별 들여쓰기). §6.3 규정 배치:
      제목(5칸, 점역자주 밖·§6.3.3(1)) → 유형+짧은 설명(점역자주·§6.3.4(1)) → 전사 항목(위계 들여).
    """
    lines: list[str] = []
    indents: list[int] = []
    title = (title or "").strip()
    desc = (desc or "").strip()
    desc = _strip_dup_type(desc, label)
    head = f"{label}: {desc}" if (desc and not _same_gist(desc, title)) else label
    if _WRAP_STYLE == "box":
        # box(A/B): 블록 전체를 글상자로 — 제목은 위 테두리 안(NLD-1.2.5), 유형/설명은 첫 줄.
        lines.append(f"<!상자>{title}<!/상자>"); indents.append(0)
        lines.append(head); indents.append(0)
    else:
        if title:
            lines.append(title); indents.append(_TITLE_INDENT)      # §6.3.3(1) 제목 5칸(plain)
        # ⚠ 제목이 `모식도, …` 처럼 유형을 밝혀도 이 머리줄을 빼지 않는다(2026-09-02 확인).
        #   위 줄은 **원본에 인쇄된 제목**이고 이 줄은 규정 §6.3.4(1)이 요구하는
        #   점역자 주 유형 제시어다 — 성격이 다르다. 조항 원문: "원본 제목에 '사진',
        #   '그림' 등과 같은 시각 자료 유형 제시어가 없더라도 점역자 주표를 사용하여
        #   시각 자료 유형을 표기한다." gold 도 같다(도형 그림 11건 전부 `그림:`).
        #   한때 이를 중복으로 보고 생략했다가, 묵자 미리보기만 보고 오독한 것이라 되돌렸다.
        # ★ 2026-09-07 정정 — 머리줄이 **앞 빈칸 0(=1칸)** 이었다(원장 C-D3).
        #   「점자 도서 제작 지침」 제3장 제2절 4)(1)·(2) L2367-2369·L2383-2385
        #   ("제목의 다음 줄 **3칸에서 시작하여** 점역자 주표 ,' ,' 안에 '시각 자료 유형'을
        #    적고, 쌍점과 원본 자료의 내용을 이어 적는다") · 같은 절 (3)①② L2400-2401·L2473-2474.
        #   gold 원본 BRF 전수(corpus/pages/braille 18,892쪽 · 시각 머리줄 4,183건) 실측:
        #   **3칸 81.0%(3,388) · 5칸 18.9%(791) · 1칸 3건(0.07%)**. 규정·gold 어느 쪽에도
        #   1칸이 없었다. 값은 `_OUTLINE_BASE` 와 같은 3칸이라 상수를 함께 쓴다.
        #   ⚠ 2026-08-25 주석의 "0칸 66.4%" 를 여기 근거로 읽지 말 것 — 그것은 **전 코퍼스
        #     모든 줄**의 분포다(재현: test_data/output 1,131쪽 전 줄 = 0칸 66.1% · 2칸 31.2%).
        #     그 코퍼스에는 점역자 주표 `,'` 가 통틀어 **1회**뿐이라 머리줄을 잴 수가 없다.
        # ★ 2026-09-08 원장 C-D4 채택 — 점역자 주표는 **유형 낱말만** 감싼다.
        #   도서지침 3장 2절 4)(1) L2368 "점역자 주표 ,' ,' 안에 '시각 자료 유형'을 적고,
        #   쌍점 \"1과 원본 자료의 내용을 이어 적는다" — 규정 예3-19 원본 BRF 도 `,'@["o5,'"1`
        #   로 주표를 닫고 그 뒤에 쌍점이 온다. gold 관행은 반대(주 안 97.4%)지만 조항이
        #   명확하므로 규정을 따른다(대표 지시 2026-07-29·2026-09-08).
        #   `diagram_opt` 골격 8종은 처음부터 이 꼴이었다 — 이제 두 갈래가 한 꼴이 된다.
        # ★ **만화만 예외로 설명까지 주 안이다**(원장 C-D6, 대표 지시 2026-09-08).
        #   조문(자료지침 §5.3.1(1) L2811 "한 칸 띈 후")은 **원본에 만화 제목이 있을 때**를
        #   말한다. 우리가 그 자리에 넣는 것은 제목이 아니라 §5.3.1(2)의 **장면 설정 설명**이라
        #   조문이 다루는 자리가 아니다. 게다가 조문과 예시가 갈린다 — 같은 지침 예5-4·5-5 는
        #   `,'만화"1`(쌍점·주 안), 도서지침 예3-53 도 쌍점을 쓴다. gold 도 10/11 이 쌍점·주 안.
        #   조문↔예시가 갈리면 "규정이 모호" 쪽이고 그때는 관행을 따른다(대표 지시 2026-07-29).
        #   ⚠ 되돌리지 말 것 — 조문 한 줄만 읽고 쌍점을 뺐다가 이 주석대로 되돌렸다.
        head_line = _oneline(head)
        head_line = (f"<!{_TAGS.TN}>{head_line}<!/{_TAGS.TN}>" if kind == "만화"
                     else f"<!{_TAGS.TN}>{label}<!/{_TAGS.TN}>" + head_line[len(label):])
        lines.append(head_line)
        indents.append(_CARTOON_HEAD_BASE if kind == "만화" else _OUTLINE_BASE)
        tn_from = len(lines) - 1        # 머리줄 자리(장면 표시 감쌀 때 기준점)
    # ⚠ 여기에 "하위에 속한 항목을 2칸씩 들여 쓰기함" 고지를 붙였다가 뺐다(2026-08-12 대표 지시).
    #   점역자 주는 **일반적이지 않은 처리**를 했을 때 쓰는 것이다 — 표를 전치했다거나,
    #   반복되는 문구를 축약했다거나. 위계를 들여쓰기로 펴는 것은 점자 조판에서 일반적이라
    #   매번 알릴 일이 아니다. 알릴수록 32칸 지면만 먹고 정작 봐야 할 고지가 묻힌다.
    #   (정본 예6-22가 조직도에 그 말을 쓰는 것은 조직도가 도형을 잃기 때문이다 —
    #    그 자리는 `diagram_opt`가 따로 낸다.)
    for level, text in items or []:
        text = (text or "").strip()
        if not text:
            continue
        # ★ 머리줄과 견줄 때는 **제시어를 떼고** 본다(2026-09-02).
        #   head 는 `그림: 퍼킨스 점자 타자기` 꼴이라 앞의 `그림:` 이 붙은 채로 견주면
        #   `퍼킨스 점자 타자기 사진` 과 포함 관계가 깨져 같은 말이 두 번 실렸다
        #   (테스트_이미지 7쪽: 머리줄 + `…사진` + `점자를 입력하는 기계식 타자기` 세 줄).
        # ⚠ 제시어를 뗀 나머지가 너무 짧으면 견주지 않는다. `그림: 설명` 처럼 머리줄이
        #   한 낱말이면 그 낱말을 품은 멀쩡한 항목까지 지워진다(실측: "본문에 없는 설명
        #   항목입니다" 가 `설명` 에 걸렸다).
        bare = _strip_type_word(head)
        if (_same_gist(text, title) or _same_gist(text, head)
                or (len(_gist(bare)) >= _GIST_MIN_LEN and _same_gist(text, bare))):
            continue                      # 제목·유형 줄을 그대로 되풀이한 항목은 지운다
        if _dup_of_body(text, body_texts):
            continue                      # 본문에 이미 있는 글자는 설명에서 뺀다(원장 C-78)
        lines.append(text); indents.append(_OUTLINE_BASE + _OUTLINE_STEP * max(0, level))  # 전사 §6.3.4(2)①
    if _WRAP_STYLE == "box":
        lines.append("<!상자끝><!/상자끝>"); indents.append(0)
    else:
        # ★ 줄마다 안/밖을 표시만 하고, 태그 짓기는 아래 한 자리에 맡긴다(2026-09-08).
        #   한 구간을 감싼 **뒤에** 장면 줄을 또 감싸면 같은 줄에서 두 손질이 겹쳐
        #   `<!주>장면 1<!/주><!/주>` 가 된다(중첩·닫는 태그 둘). 대표 QA 실물이 그 꼴이었다.
        #   ⚠ 조항이 있는 자리만 주 안으로 옮긴다(대표 지시 2026-09-08 "조항 없는
        #     자리는 강제하지 말라"). 머리줄의 유형 낱말(§6.3.4(1)·위에서 이미 감쌌다) ·
        #     장면 표시(§5.3.3(1)) · 조립기가 감싸 보낸 행동·상황(§5.3.3(6)(7)) 셋뿐이다.
        #     "대사가 아니면 다 주 안" 으로 넓혔다가 규정 예3-54의 `……` 와 깨진
        #     장면 표시까지 주 안으로 끌려 들어가 주표위치가 어긋났다(게이트 -1건).
        inside = [False] * len(lines)
        pre_tagged = [k for k, ln in enumerate(lines)
                      if k > tn_from and f"<!{_TAGS.TN}>" in ln]
        # ★ 2026-09-08 원장 C-D4 채택 — **머리줄은 위에서 유형 낱말만 감쌌다.**
        #   쌍점부터 뒤(짧은 설명·전사 항목)는 도서지침 3장 2절 4)(1) L2368 대로 주표
        #   **밖**이다. 그래서 머리줄에서 시작해 아래로 흐르던 주 구간(`tn_to`)이 없어졌다.
        #   여기서 주로 감싸는 것은 조항이 따로 있는 두 자리뿐이다 —
        #     · 장면 표시(`장면 1`)              §5.3.3(1) L2820-2821 (점역자가 붙인 표시)
        #     · 조립기가 이미 주로 감싸 보낸 줄  §5.3.3(6)(7) 행동·상황
        #   ⚠ 조항 없는 자리를 줄 모양으로 짐작해 주 안에 넣지 말 것(대표 지시 2026-09-08).
        for k in range(tn_from + 1, len(lines)):
            if _SCENE_LINE.match(lines[k].strip()) or k in pre_tagged:
                inside[k] = True
        lines = [_TAGS.normalize_tn_spans(ln).replace(f"<!{_TAGS.TN}>", "")
                 .replace(f"<!/{_TAGS.TN}>", "") if inside[k] else ln
                 for k, ln in enumerate(lines)]   # 겹치지 않게 기존 태그를 걷고 다시 짓는다
        # 잇닿은 주-안 줄은 **한 덩이**로 감싼다 — §6.3.4(1)이 유형 제시어부터 자료
        # 내용까지를 한 주표 안에 두라고 하고, NLD-1.2.6 도 "원본과 달라진 내용"을 한
        # 덩이로 본다. 줄마다 따로 감싸면 32칸 지면에 주표만 늘어난다.
        k = 0
        while k < len(lines):
            if not inside[k]:
                k += 1
                continue
            j = k
            # ★ 장면 줄은 **언제나 제 주표를 연다**(2026-09-08). §5.3.3(1) L2820-2821
            #   "'장면 1'의 형식으로 5칸에 점역자 주표를 사용하여 적는다" — 만화 제목 주
            #   (§5.3.1(1) L2811)와 별개 주다. 인접이라는 이유로 머리줄 주에 묶으면 첫
            #   장면만 흡수되고 둘째부터 갈라져 한 문서에 형식이 둘로 선다.
            #   ⚠ 장면 줄에서 **시작한** 주는 뒤를 계속 먹는다 — §5.3.3(7)이 "장면 번호와
            #     함께 점역자 주표 안에 (행동) 설명을 추가한다"고 하므로 그 둘은 한 주다.
            while (j + 1 < len(lines) and inside[j + 1]
                   and not _SCENE_LINE.match(lines[j + 1].strip())):
                j += 1
            lines[k] = f"<!{_TAGS.TN}>{lines[k]}"
            lines[j] = f"{lines[j]}<!/{_TAGS.TN}>"
            k = j + 1
    return _TAGS.normalize_tn_spans("\n".join(lines)), indents


