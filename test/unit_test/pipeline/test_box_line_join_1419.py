"""#1419 — 줄 잇기가 글상자 테두리 줄(여는 · 닫는 상자 태그 쌍)에 다음 줄을 붙이지 않는다.

위 테두리는 줄 첫 칸부터 마지막 칸까지 적는 한 줄이다(「점자 도서 제작 지침」 1장 2절 5. 2)(1), 재추출 392~393행).
잇기 판정은 종전 그대로 두고, 이은 줄 맨 앞의 테두리 줄 뒤만 줄을 바꾼다.
"""
from app.core.pipeline import _join_wrapped_lines as join

TOP = "<!상자><!/상자>"


def test_위_테두리_줄_뒤_본문은_새_줄로_남는다():
    src = f"{TOP}\n나의 부친인 이수광은 조선의 학자로서 여러 나라의 사신들과 만나\n교류하였다."
    assert join(src) == f"{TOP}\n나의 부친인 이수광은 조선의 학자로서 여러 나라의 사신들과 만나 교류하였다."


def test_제목_든_위_테두리_줄도_새_줄로_남는다():
    src = "<!상자>본문 220~223쪽<!/상자>\n01 ④  02 ①  03 ②  04 ②\n<!상자끝><!/상자끝>"
    assert join(src) == "<!상자>본문 220~223쪽<!/상자>\n01 ④  02 ①  03 ②  04 ② <!상자끝><!/상자끝>"


def test_겹친_상자의_여는_줄은_한_줄씩_남는다():
    src = (f"{TOP}\n<!상자2><!/상자2>\n포르투갈과 에스파냐의 신항로 개척\n<!주>그림 생략<!/주>\n"
           "<!상자끝2><!/상자끝2>\n<!상자끝><!/상자끝>")
    assert join(src).startswith(f"{TOP}\n<!상자2><!/상자2>\n포르투갈과 에스파냐의 신항로 개척\n")


def test_요소_가운데서_열리는_상자도_새_줄로_남는다():
    # 한 요소에 상자 둘(앞 상자 닫힘 → 새 상자 열림)이면 테두리 줄이 둘째 줄 이후에 온다.
    src = ("앞 상자의 끝 줄\n<!상자끝><!/상자끝>\n" + TOP
           + "\n나의 부친인 이수광은 조선의 학자로서 여러 나라의 사신들과 만나\n교류하였다.")
    assert join(src) == ("앞 상자의 끝 줄\n<!상자끝><!/상자끝>\n" + TOP
                         + "\n나의 부친인 이수광은 조선의 학자로서 여러 나라의 사신들과 만나 교류하였다.")


def test_본문_줄끼리_잇기_판정은_종전과_같다(monkeypatch):
    # 태그 줄을 떼고 다시 판정하면 짧아진 첫 본문 줄 때문에 `을:` · `병:` 앞 줄바꿈 판정이 바뀐다(전수 12요소).
    src = (f"{TOP}\n갑: 연구 결과의 타당성 검증보다는 현상의 기술에 유용하다.\n"
           "을: 연구 대상자가 구성하는 생활 세계에 연구의 초점을 맞춘다.\n"
           "병: 방법론적 일원론을 전제로 객관적인 관찰, 실험, 비교를 중시한다.")
    monkeypatch.setenv("BOX_LINE_NO_JOIN", "0")
    old = join(src)
    monkeypatch.setenv("BOX_LINE_NO_JOIN", "1")
    assert join(src) == f"{TOP}\n" + old[len(TOP):].lstrip(" ")


def test_줄_가운데_닫는_태그는_그대로다():
    src = "개인의 자율성을 존중하고 스스로 책임을 다하도록 강조하는 정도\n<!상자끝2><!/상자끝2>\n<!상자끝><!/상자끝>"
    assert join(src) == "개인의 자율성을 존중하고 스스로 책임을 다하도록 강조하는 정도 <!상자끝2><!/상자끝2> <!상자끝><!/상자끝>"


