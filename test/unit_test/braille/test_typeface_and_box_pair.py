"""점역자 정의 글자체표·빈칸 품은 네모 문자 쌍이 이물질로 새던 문제 (2026-09-07).

「한국 점자 규정」 제56항 [붙임](재추출본 2477~2478행)은 색상·모양으로 강조된 글자체를
제1점역자 정의 글자체표 `"- -1`(⠐⠤ … ⠤⠂) · 제2점역자 정의 글자체표 `@- -a`(⠈⠤ … ⠤⠁)로
묶는다. 역맵에 없어 그 네 셀이 BRF ASCII 그대로 본문에 남았다 —
`,-전라북도 전주-,` · `'-15,000원-a`.

제64항(2566~2567행) 네모 문자 `⠸⠦ … ⠴⠇` 는 이미 있었지만 **토큰 안에서만** 짝을 찾아,
감싼 내용에 빈칸이 있으면 여는 쪽과 닫는 쪽이 갈렸다 — `⟨2838⟩"세포 호흡l`.

전권 18,892쪽 실측: 글자체표 짝 1,770(219쪽) · 빈칸 품은 네모 문자 467(259쪽).
"""
from app.utils.braille_ascii import ascii_to_unicode
from app.utils.braille_back import decode


def _d(brf: str) -> str:
    return decode(ascii_to_unicode(brf, backtick="space")).strip()


def test_제1점역자_정의_글자체표를_벗긴다():
    # 규정 2481~2482행 — 묵자 "최명희 작가는 전라북도 전주 출신입니다."
    assert "-" not in _d(';ye}jw`.a$cz`"-.)"<~maiu`.)`.m-1`;&,qobcoi4')


def test_제2점역자_정의_글자체표를_벗긴다():
    # 규정 2489행 — 묵자 "금액 할인: 15,000원 …"
    assert _d('@{5ra`j1q"1`@-#ae1jjjp3-a') == "금액 할인: 15,000원"


def test_빈칸_품은_네모_문자_쌍을_편다():
    # 실물(EBS-E26-001 body p0025) — `⠸⠦세포 호흡⠴⠇`
    assert decode("⠸⠦⠠⠝⠙⠥⠀⠚⠥⠚⠪⠃⠴⠇") == "▯세포 호흡▯"


def test_빈칸_없는_네모_문자_쌍은_그대로_동그라미_숫자():
    # 제64항 동그라미 숫자는 토큰 첫 칸의 수표라야 펴진다 — 손대면 `▯6▯` 로 떨어진다.
    assert _d("_8#50l") == "▯⑤▯"


def test_점형표_줄의_네모_문자는_셀_그대로():
    # 제67항 점형표(⠸⠿)는 점형 그 자체를 낸다 — ES-TXT-KA0003 body p0130.
    assert decode("⠉⠝⠑⠥⠀⠼⠁⠀⠀⠸⠿⠸⠦⠼⠁⠴⠇").endswith("⠸⠦⠼⠁⠴⠇")
