"""미지셀 자리의 로마자 낱자 폴백.

한글로도 기호로도 안 풀린 셀이 로마자 낱자 점형이면 낱자로 낸다. 수식 속 변수
(`b=2`·`k=1`)가 미지셀로 나가던 자리다 — 한글은 이미 실패했으므로 잃을 것이 없다.

⚠ 토큰을 통째로 수식으로 올리는 안은 **기각했다**(코퍼스 3,000쪽 A/B — 이득 723 ·
  손해 1,199). `수컷(2n=12+XY)의` 같은 한글 섞인 줄이 통째로 로마자로 뒤집혔다.
"""
from app.utils.braille_back import decode


def test_수식_변수를_낱자로_낸다():
    assert decode("⠃⠒⠒⠼⠉") == "b=3"
    assert decode("⠅⠒⠒⠼⠁") == "k=1"


def test_한글이_풀리는_자리는_안_건드린다():
    # 한글 표가 먼저다 — 폴백은 아무것도 못 푼 뒤에만 온다.
    assert decode("⠈⠕⠊⠐⠕") == "기다리"


def test_숫자는_수표로_읽는다():
    assert decode("⠼⠙") == "4"


def test_로마자표_없이_선_대문자표를_살린다():
    # 제30항 [붙임](재추출 1480~1482행) — 한 글자 대문자는 대문자 기호표 ⠠ 를 앞에 적는다.
    # gold 001 body p0130 유전자형 `AA, Aa`. 종전엔 ⠠ 가 버려져 `AA, aa` 였다.
    assert decode("⠠⠠⠁⠁⠂⠀⠠⠁⠁") == "AA, Aa"
    assert decode("⠠⠁") == "A"
    assert decode("⠠⠍⠤⠗⠁") == "수액"     # 한글로 풀리는 ⠠(초성 ㅅ)는 그대로
