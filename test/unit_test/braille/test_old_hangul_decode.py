"""옛한글 역점역(규정 제19~25항) · 동그라미 숫자(제64항) 회귀 가드.

**순환검증 금지**: 기대값은 두 출처에서만 왔다.
  ① 「한국 점자 규정」 원문(`braille-source/text/규정_텍스트.txt` 962~1300행)의 점형표.
     제20항 순경음 비읍 ㅸ 첫소리 = `"^7`(⠐⠘⠶) · 제19항 반치음 ㅿ 첫소리 = `".`(⠐⠨) ·
     제25항 아래아 ㆍ = `"#`(⠐⠼) · 아래애 ㆎ = `"#R`(⠐⠼⠗) · 제64항 동그라미 숫자 ① = `#1`(⠼⠂).
  ② 정답 도서 실측 — 수능특강 언어와 매체 body p0239·p0035, 수학 I body p0014.
     각 줄의 재추출 묵자를 그대로 기대값으로 썼다.
"""
from __future__ import annotations

import pytest

from app.utils.braille_ascii import ascii_to_unicode
from app.utils.braille_back import decode


def test_규정_점형표_그대로다() -> None:
    """규정 BRF 표기 → 셀. 이 셀이 바뀌면 아래 기대값이 전부 무효다."""
    assert ascii_to_unicode('"#') == "⠐⠼"        # 제25항 ㆍ
    assert ascii_to_unicode('"#R') == "⠐⠼⠗"      # 제25항 ㆎ
    assert ascii_to_unicode('"^7') == "⠐⠘⠶"      # 제20항 ㅸ 첫소리
    assert ascii_to_unicode('".') == "⠐⠨"        # 제19항 ㅿ 첫소리
    assert ascii_to_unicode("#1") == "⠼⠂"        # 제64항 ①


# (라벨, 셀, 기대 텍스트) — 기대는 재추출 묵자 실측값이다.
CASES = [
    ("아래아-p0239", "⠘⠐⠼⠐⠐⠼⠑⠕", "ᄇᆞᄅᆞ미"),
    ("아래아받침-p0239", "⠈⠥⠊⠐⠼⠂", "고ᄃᆞᆯ"),
    ("옛자음-단독-p0035", "⠠⠦⠿⠐⠘⠶⠐⠀⠿⠐⠨⠴⠄", "‘ㅸ, ㅿ’"),
    ("옛모음-단독-p0035", "⠿⠐⠼⠐⠀⠿⠪", "ㆍ, ㅡ"),
    ("아래애-단독-p0035", "⠿⠐⠼⠗", "ㆎ"),
    ("옛자음+약자", "⠐⠘⠶⠵", "ᄫᅳᆫ"),           # 제20항 — 정방향이 '은'을 약자로 적는다
    ("ㅇ초성-관행-p0021", "⠠⠦⠛⠐⠼⠂⠴⠄", "‘ᄋᆞᆯ’"),   # 관행: 첫소리 ㅇ 을 ⠛ 로 적는다
    ("ㅇ초성없음-p0021", "⠠⠦⠐⠐⠼⠂⠴⠄", "‘ᄅᆞᆯ’"),
    ("동그라미숫자-p0014", "⠼⠂⠀⠜⠼⠃⠀⠀⠼⠆⠀⠜⠼⠉", "① √2  ② √3"),
]


@pytest.mark.parametrize("label,cells,want", CASES, ids=[c[0] for c in CASES])
def test_옛한글_동그라미_역점역(label: str, cells: str, want: str) -> None:
    assert decode(cells) == want, f"{label}: {decode(cells)!r}"


def test_수_런_안의_쉼표는_아래아가_아니다() -> None:
    """⠐⠼ 는 `쉼표 + 다음 수의 수표`와 셀이 같다 — 전 코퍼스 862건 중 395건이 그쪽이다."""
    assert decode("⠼⠙⠐⠼⠁⠐⠼⠃") == "4,1,2"


@pytest.mark.parametrize("cells,want", [
    # ★ 2026-09-04 정정 — 기대값이 결함을 담고 있었다(C-104). 코퍼스 실물은 이 토큰이
    #   더 긴 수식의 일부다: `⠋⠤⠦⠁⠴⠐⠼⠃⠒⠒⠼⠑⠐⠼⠃⠒⠒⠼⠁⠚`(HS-REF-T25-014 body/p0015).
    #   종전 `카-"a”,2=5,2=10` 은 뜻이 안 통하고, 수식으로 읽으면 `f-(a)·2=5·2=10` 이다.
    #   겹친 관계 기호 ⠒⠒ 를 수식 신호로 보면서 ⠐ 가 가운뎃점(곱셈)으로 바로잡혔다.
    #   이 테스트의 취지(⠐⠼ 가 음절 한복판에서 아래아가 아니다)는 그대로 지킨다.
    ("⠦⠁⠴⠐⠼⠃⠒⠒⠼⠑", "(a)·2=5"),        # 수식 가운뎃점 + 다음 수 (풍산자 고등수학 2)
    ("⠭⠐⠼⠃", "옥,2"),                   # 변수 뒤 쉼표 + 수
])
def test_음절_한복판의_쉼표는_아래아가_아니다(cells: str, want: str) -> None:
    """초성 없는 아래아는 **낱말 경계에서만** 편다.

    ⠐⠼ 는 `쉼표 + 다음 수의 수표`와 셀이 같다. 전 코퍼스 실측: 초성 없는 자리 221건 중
    경계 밖 110건이 전부 수식·각주 번호였다(수학책 `”,2=` · 동백꽃 각주 `,41`).
    """
    assert decode(cells) == want


def test_로그_밑은_동그라미_숫자가_아니다() -> None:
    """⠸⠼⠆ 는 「수학 점자」 제46항 log₂ 다 — ② 로 펴면 안 된다."""
    assert decode("⠸⠼⠆⠭") == "log 2옥"


def test_묶음_안_동그라미_낱자는_그대로() -> None:
    """제64항 동그라미 문자 틀 ⠶ ⠶ 는 종전대로 — 이 고침이 건드리지 않는다."""
    assert decode("⠶⠿⠂⠶") == "㉣"
