"""옛한글(중세 국어) 첫가끝 자모 점역 회귀 가드 — 규정 제3장 「옛 글자」.

이 파일이 지키는 것: 완성형으로 조합되지 않는 옛 음절이 **사라지지 않는 것**.
`ᄒᆞ야`(ᄒ + ᆞ + 야)는 braillify가 거부해 _safe_to_unicode의 "변환 불가 글자 제거"가
음절째 지웠다 — 출력이 `야`뿐이었다(2026-09-03 실측). 예외도 플래그도 없는 무성 삭제라
점역사가 원문과 대조하지 않으면 발견할 수 없다.

**순환검증 금지**: 기대값은 두 출처에서만 왔다.
  ① 「한국 점자 규정」제19~25항 — 옛 글자표 ⠐, 아래아 ㆍ=⠐⠼, 반치음 첫소리 ㅿ=⠐⠨,
     순경음 비읍 ㅸ=⠐⠘⠶, 시옷기역 ㅺ=⠐⠠⠈(`braille-source/text/규정_텍스트.txt` 970행~).
  ② 정답 도서 실측 — 언어와 매체 p035 gold `⠑⠂⠠⠠⠐⠼⠑⠕`(말ᄊᆞ미),
     p082 gold `⠠⠱⠐⠘⠶⠮`(셔ᄫᅳᆯ). 코퍼스 27쪽 235런 중 216(91.9%)이 gold와 일치하고,
     남은 19는 묵자 재추출 오독이다(`어드ᄫᅳᆫ`→`ᄫᅩᆫ` 등).
"""
from __future__ import annotations

import pytest

from app.ai.braille.translator import translate_plain


@pytest.mark.parametrize("text, expected", [
    ("말ᄊᆞ미", "⠑⠂⠠⠠⠐⠼⠑⠕"),      # gold 언어 p035 — ㅆ 초성 + 아래아
    ("셔ᄫᅳᆯ", "⠠⠱⠐⠘⠶⠮"),          # gold 언어 p082 — 순경음 ㅸ + 약자 '을'
    ("ᄒᆞ야", "⠚⠐⠼⠜"),               # 초성 ㅎ + 아래아
    ("ᅀᆞᆷ", "⠐⠨⠐⠼⠢"),              # 반치음 첫소리(제19항)
    ("ᄭᅮᆷ", "⠐⠠⠈⠍⠢"),              # gold 언어 p035 — 합용 병서 ㅺ(제22항)
])
def test_old_syllable_keeps_cells(text, expected):
    assert translate_plain(text) == expected


def test_old_jamo_is_not_silently_dropped():
    """음절이 통째로 사라지던 회귀 — 옛 자모 자리에 셀이 있어야 한다."""
    assert translate_plain("ᄒᆞ야") != translate_plain("야")


def test_modern_text_untouched():
    """첫가끝 자모가 없는 줄은 종전 경로 그대로(약자·약어 보존)."""
    assert translate_plain("하늘") == "⠚⠉⠮"


# 제25항 옛 모음자 — 규정 표 전수(`braille-source/text/한국 점자 규정_재추출.txt` 1239~1254행: 글자 · BRF).
# 첫소리 ㅇ 은 적지 않으므로(아래 예 `ᄋᆡᄆᆡᄒᆞᆫ` · `집거ᄋᆔ라`) `ᄋ + 모음` 이 표의 점형 그대로 나와야 한다.
# 종전 표는 첫가끝 코드값을 잘못 걸어 ㆉ 를 ㆇ 로 적고, ㆇ · ㆈ · ㆊ · ㆋ · ㆌ 는 표에 없어 음절째 지웠다(#1093).
@pytest.mark.parametrize("vowel, expected", [
    ("\u119e", "⠐⠼"),      # 1239 · 1247 `"#`   ㆍ 아래아
    ("\u11a1", "⠐⠼⠗"),    # 1240 · 1248 `"#R`  ㆎ 아래애
    ("\u1184", "⠸⠬⠜"),    # 1241 · 1249 `_+>`  ㆇ 요야
    ("\u1185", "⠸⠬⠜⠗"),  # 1242 · 1250 `_+>r` ㆈ 요얘
    ("\u1188", "⠸⠬⠕"),    # 1243 · 1251 `_+o`  ㆉ 요이
    ("\u1191", "⠸⠩⠱"),    # 1244 · 1252 `_%:`  ㆊ 유여
    ("\u1192", "⠸⠩⠌"),    # 1245 · 1253 `_%/`  ㆋ 유예
    ("\u1194", "⠸⠩⠕"),    # 1246 · 1254 `_%o`  ㆌ 유이
])
def test_old_vowel_regulation_table(vowel, expected):
    assert translate_plain("\u110b" + vowel) == expected


# 제25항 예 여덟 줄 전부(같은 파일 1264~1283행, BRF 를 셀로 옮김). 한자는 규정 점자에 안 적혀 뺐다.
# 종전 출력: 1270 은 ㆉ 가 ㆇ 로 틀렸고, 나머지 넷은 옛 모음 음절이 빠졌다. 1275 는 한 런이 통째로 사라져
# 빈 출력이었다. ★ 빠지는 것은 틀리는 것보다 나쁘다 — 점역사가 원문과 맞대지 않으면 찾을 단서가 없다.
@pytest.mark.parametrize("text, expected", [
    ("ᄀᆞᅀᆞᆯ", "⠈⠐⠼⠐⠨⠐⠼⠂"),              # 1264~1265 `@"#"."#1`
    ("ᄋᆡᄆᆡᄒᆞᆫ", "⠐⠼⠗⠑⠐⠼⠗⠚⠐⠼⠒"),          # 1266~1267 `"#re"#rj"#3`
    ("ᄉᆈ고기", "⠠⠸⠬⠕⠈⠥⠈⠕"),              # 1270~1271 `,_+o@u@o` — 종전 ⠠⠸⠬⠜⠈⠥⠈⠕
    ("ᄃᆑᆫ륜ᅌᅪᇰ", "⠊⠸⠩⠱⠒⠐⠩⠒⠐⠙⠧⠐⠲"),      # 1272 `i_%:3"%3"dv"4` — 종전 ᄃᆑᆫ 빠짐
    ("ᅌᆑᇰ야ᇰ", "⠐⠙⠸⠩⠱⠐⠲⠜⠐⠲"),          # 1275~1276 `"d_%:"4>"4` — 종전 빈 출력
    ("기슭섬 ᄎᆒ", "⠈⠕⠠⠮⠁⠠⠎⠢⠀⠰⠸⠩⠌"),      # 1277 `@o,!a,s5`;_%/`(백틱 = 빈칸) — 종전 ᄎᆒ 빠짐
    ("집거ᄋᆔ라", "⠨⠕⠃⠈⠎⠸⠩⠕⠐⠣"),          # 1280~1281 `.ob@s_%o"<` — 종전 ⠨⠕⠃⠈⠎⠐⠣(ᄋᆔ 빠짐)
    ("술 ᄎᆔᄒᆞ야", "⠠⠯⠀⠰⠸⠩⠕⠚⠐⠼⠜"),        # 1282~1283 `,&`;_%oj"#>` — 종전 ⠠⠯⠀⠜
])
def test_old_vowel_regulation_examples(text, expected):
    assert translate_plain(text) == expected
