"""두 줄로 나뉜 긴 숫자의 연결표 — 「한글 점자」 제42항.

"일곱 자리 이상의 긴 숫자를 두 줄에 나누어 적을 때에는 위 줄 끝에 연결표 ⠠ 을 적고,
아래 줄의 첫머리에는 수표를 다시 적지 않는다. 이때 아래 줄에는 세 자리 이상의 숫자가
나와야 한다."(재추출본 1946~1948행) · [붙임] 1952행 "자릿점이 있는 숫자의 경우,
자릿점 뒤에 연결표를 적는다."

연결표를 버리면 아래 줄 숫자가 수표 문맥을 잃고 한글 음절로 떨어진다.
"""
import pytest

from app.utils.braille_back import decode


@pytest.mark.parametrize("cells, want", [
    # 규정 예문 1949~1951행 — 택배 송장 번호는 123456789012입니다.
    ("⠼⠁⠃⠉⠙⠑⠋⠛⠓⠊⠠\n⠚⠁⠃⠕⠃⠉⠕⠊⠲", "123456789012입니다."),
    # 규정 예문 1953~1955행 [붙임] — 당첨금: 10,000,000,000원
    ("⠼⠁⠚⠂⠚⠚⠚⠂⠚⠚⠚⠂⠠\n⠚⠚⠚⠏⠒", "10,000,000,000원"),
    # 줄 끝 채움 셀이 붙어도 이어진다(BRF 32칸 조판)
    ("⠼⠁⠃⠉⠙⠑⠋⠛⠓⠊⠠⠀⠀\n⠚⠁⠃⠕⠃⠉⠕⠊⠲", "123456789012입니다."),
])
def test_제42항_연결표로_이어진다(cells, want):
    assert decode(cells) == want


@pytest.mark.parametrize("cells", [
    "⠼⠁⠃⠉⠠\n⠚⠁",          # 아래 줄이 두 자리 — 규정은 세 자리 이상을 요구한다
    "⠼⠁⠃⠠\n⠚⠁⠃",          # 위 줄 숫자 런이 너무 짧다(긴 숫자가 아니다)
    "⠼⠁⠃⠉⠙⠑⠋⠠\n⠈⠪⠐⠕",   # 아래 줄 첫머리가 숫자가 아니다
])
def test_조건에_안_맞으면_안_잇는다(cells):
    assert "\n" in decode(cells)
