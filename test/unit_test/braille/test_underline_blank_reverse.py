"""밑줄 빈칸 `_-`(⠸⠤) 역규칙 회귀 가드 + 한글표 줄 넘김 비회귀.

이 파일이 지키는 것
  1. 밑줄 빈칸 ⠸⠤ 를 밑줄 `_` 한 개로 읽는 것 (규정 제73항).
     종전에는 ⠸ 가 미지셀로 새고 ⠤ 가 붙임표로 읽혀 `X⟨2838⟩-` 꼴이 나갔다.
     정방향은 이 셀을 이미 낸다 — translator._TAGS.BLANK_RULE · symbol_table `"_"` ·
     layout_braille._UNDERLINE_BLANK_MARKER. 역맵에만 빠져 있던 한쪽 짝이다.
  2. 그 곁에 있는 붙임표(⠤)·도형 반복 틀(⠸+같은 셀xN+⠇)이 안 깨지는 것.
  3. 한글표·한글 종료표(제39항)가 **줄을 넘어도** 벗겨지는 것.

**순환검증 금지** — 기대값의 출처
  · 규정 예문: 「한국 점자 규정」 제73항 '빈칸'(규정_텍스트.txt 2941~2962행)의 점자를
    그대로 넣는다. "밑줄 빈칸은 길이와 관계 없이 `_-`을 1개 적는다"(「점자 도서 제작
    지침」 2장 2절 3-(2))이므로 **점자에 원래 길이가 없다.** 그래서 되돌린 묵자는 규정
    예문의 긴 밑줄이 아니라 `_` 한 개다 — 복원할 수 없는 것을 지어내지 않는다.
    [다만] 항은 빈칸 개수만큼 적으므로 `_-_-` 는 `__` 두 개로 돌아온다.
  · 코퍼스 실물: EBS-E26-004/body/p0045(SNS 계정명)·EBS-E26-001/ans/p0028.
    재추출 묵자가 각각 `책사랑_△△`·`$2n=6+X\\_$` 로 **밑줄 한 개**를 적는다
    (전 코퍼스 1,361쪽 밑줄런 9,229건이 전부 길이 1).
"""
from __future__ import annotations

import pytest

from app.utils.braille_ascii import ascii_to_unicode
from app.utils.braille_back import decode


@pytest.mark.parametrize("brf, expected", [
    # 제73항 예문 — "다음 ___에 적절한 단어를 넣으세요."
    ("i<{5`_-n`.?.tj3`i3s\"!`cs0{,n+4", "다음 _에 적절한 단어를 넣으세요."),
    # 제73항 [다만] — 빈칸 개수를 나타낼 때는 그 수만큼 적는다
    ("l.,]s`;rm@o\"1`@u,]_-_-", "사자성어 채우기: 고성__"),
    # 제73항 [붙임] — 표시 문자를 먼저 적고 밑줄 빈칸 기호를 붙여 적는다
    ("o1,o\"1`7=a7_-", "일시: ㉠_"),
])
def test_규정_제73항_밑줄_빈칸(brf, expected):
    assert decode(ascii_to_unicode(brf, backtick="space")) == expected


@pytest.mark.parametrize("cells, expected", [
    # EBS-E26-004/body/p0045 — SNS 계정명. 밑줄 빈칸 + 도형 반복 틀이 잇달아 온다.
    ("⠰⠗⠁⠇⠐⠣⠶⠸⠤⠸⠬⠬⠇", "책사랑_△△"),
    ("⠊⠠⠥⠢⠸⠤⠸⠶⠇", "다솜_□"),
])
def test_코퍼스_실물_밑줄_빈칸(cells, expected):
    assert decode(cells) == expected


def test_붙임표는_그대로_붙임표다():
    """⠤ 단독은 붙임표(-)다 — ⠸⠤ 를 넣었다고 여기까지 번지면 안 된다."""
    assert decode("⠤") == "-"
    assert decode("⠸⠤") == "_"


def test_도형_반복_틀은_안_깨진다():
    """제57·58항 틀은 종전대로. 밑줄 빈칸이 앞에 붙어도 각각 읽힌다."""
    assert decode("⠸⠬⠬⠇") == "△△"
    assert decode("⠸⠤⠸⠬⠬⠇") == "_△△"


# ── 한글표·한글 종료표(제39항) 줄 넘김 비회귀 ────────────────────────────────
# `decode` 는 줄을 쪼개기 **전에** 이 짝을 벗긴다(v3.2.36). 점자책이 32칸 조판이라
# 한글 구간이 줄을 넘는 일이 흔하다 — 전 코퍼스 18,892쪽에서 ⠸⠷ 2,305 · ⠸⠾ 2,293 중
# 짝이 안 맞아 남는 것은 34건(1.5%)뿐이다. 그 성질을 여기서 못 박는다.
def test_한글표가_줄을_넘어도_벗겨진다():
    out = decode("⠸⠷⠈⠩⠐⠣\n⠚⠣⠺⠸⠾")
    assert "⟨2838⟩" not in out
    assert "\n" in out                       # 줄바꿈은 그대로 보존한다


def test_닫는_표가_먼저_오는_줄은_본문을_안_먹는다():
    """앞 줄에서 이어진 닫는 표가 먼저 나와도 뒤따르는 여는 표와 짝지어 삼키면 안 된다."""
    solo = decode("⠈⠩⠐⠣")                    # 표 없이 읽은 같은 글
    out = decode("⠈⠩⠐⠣⠸⠾⠀⠸⠷⠈⠩⠐⠣")
    assert out.startswith(solo)               # 앞쪽 본문이 그대로 남는다
    assert out.endswith(solo)                 # 뒤쪽 본문도 그대로 남는다
