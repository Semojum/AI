"""홑 곱셈표 ⠡ — 「수학 점자」 제2항.

한글 약자 '연'과 점형이 같지만 **앞뒤가 모두 공백일 때만** 곱셈표다
(제11항 "수식은 앞뒤를 두 칸씩 띄어 쓴다").

실측(코퍼스 2,500쪽): 홑 ⠡ 110건이 전부 가계도 교배 기호이고, 약자 '연'으로 쓰인
붙은 ⠡ 는 18,316건 — 공백 조건에서 완전히 갈린다.
gold 시각자료 1,166블록에서 90개가 복원됐다.
"""
from app.utils.braille_back import decode


def test_앞뒤_공백이면_곱셈표():
    assert decode("⠈⠕⠀⠡⠀⠈⠕") == "기 × 기"


def test_붙어_있으면_약자_연():
    assert decode("⠈⠡⠕") == "견이"


def test_홀로_있으면_종전대로():
    # 앞뒤에 공백 셀이 없으면 판정 근거가 없다 — 건드리지 않는다.
    assert decode("⠡") == "연"


def test_가계도_교배_기호():
    d = decode("⠦⠼⠁⠀⠡⠀⠦⠼⠃")
    assert "×" in d
