"""로마자 바로 뒤 숫자 앞 ⠲ 는 마침표다 (#1199, 「한글 점자」 제35항).

제35항(재추출 1720행): 로마자와 숫자가 이어 나올 때에는 로마자 종료표를 적지 않는다(예 `MP3` = `0,,mp#c`).
그래서 로마자 바로 뒤 ⠲⠼ 의 ⠲ 는 종료표일 수 없고 마침표다. 종전에는 종료표로 먹어 `p15` · `No1` 로 나갔다.
"""
from app.utils.braille_back import decode


def test_쪽_번호_약자():
    assert decode("⠈⠬⠈⠧⠠⠎⠀⠴⠏⠲⠼⠁⠑⠀⠰⠣⠢⠈⠥") == "교과서 p.15 참고"


def test_번호_약자():
    assert decode("⠴⠠⠝⠕⠲⠼⠁") == "No.1"


def test_제35항_예문은_그대로():
    # 종료표 없이 숫자가 붙는 규정 예문 — 마침표를 지어내지 않는다.
    assert decode("⠴⠠⠠⠍⠏⠼⠉⠀⠙⠮⠐⠝⠕⠎") == "MP3 플레이어"
    assert decode("⠴⠠⠁⠼⠙⠬⠶⠨⠕") == "A4용지"
