"""로마 숫자는 자리와 상관없이 로마자표형이다(제36항, 재추출 1753~1794행).

2026-08-27 에 섹션번호 자리(줄머리 + 마침표)에만 남겼던 낱자 점형 관행을 지웠다(#1373). 그 근거로 적었던 동결 val
쪽들(사회문화 p046 · p116 · p154 · 세계사 p016)의 gold 가 전부 로마자표형이었고, 2027 dev · val 섹션번호 13자리도
gold 13/13 로마자표형이다. 낱자 점형을 쓰면 로마자표 ⠴ 가 빠져 그 셀이 한글로 읽힌다.
"""
from app.ai.braille.translator import translate_tagged_text as T


def test_본문_속_로마숫자는_로마자표를_붙인다():
    """gold EBS-E26-001 body p0089 49행: ⠴⠠⠊⠈⠔⠠⠠⠊⠊⠊⠲"""
    o = T("경로 Ⅰ~Ⅲ을")
    assert "⠴" in o and "⠲" in o


def test_섹션번호도_로마자표형():
    """줄머리 + 마침표(섹션번호). gold 2027 dev 001 body p0018 `Ⅱ. 사람의 물질대사` = ⠴⠠⠠⠊⠊⠲⠀⠇⠐⠣⠢⠺…"""
    assert T("Ⅱ. 사람의 물질대사").startswith("⠴⠠⠠⠊⠊⠲⠀⠇⠐⠣⠢⠺")


def test_줄머리라도_마침표가_없으면_로마자표형():
    """gold p0002 1행은 'IV 유전'을 ⠴⠠⠠⠊⠧⠲ 로 적는다 — 공백은 섹션번호 신호가 아니다."""
    assert T("Ⅳ 유전").startswith("⠴⠠⠠⠊⠧⠲")
