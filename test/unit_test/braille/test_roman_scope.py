"""로마 숫자 낱자 점형은 **섹션번호 자리에만** (원장 훑기 ⚠확정, 2026-08-27).

근거 범위 = frozen 섹션번호 3쪽(사회문화 p046·154, 세계사 p016)
적용 범위 = 종전 '수식 밖 로마숫자 전부' → **줄머리 + 바로 뒤 마침표**로 좁힌다
교차 검증 = dev-2027 900쪽. 로마숫자 1,132건 중 섹션번호 19건(1.7%)
어느 코퍼스 = frozen(근거) / dev-2027(교차)

본문 속에서 낱자 점형을 쓰면 로마자표 ⠴·종료표 ⠲ 가 빠져 그 셀이 한글로 읽힌다.
"""
from app.ai.braille.translator import translate_tagged_text as T


def test_본문_속_로마숫자는_로마자표를_붙인다():
    """gold EBS-E26-001 body p0089 49행: ⠴⠠⠊⠈⠔⠠⠠⠊⠊⠊⠲"""
    o = T("경로 Ⅰ~Ⅲ을")
    assert "⠴" in o and "⠲" in o


def test_섹션번호는_낱자_점형_그대로():
    """줄머리 + 마침표. 이 자리는 종전 관행을 지킨다(회귀 방지)."""
    o = T("Ⅱ. 사람의 물질대사")
    assert o.startswith("⠠⠊⠊⠲")
    assert not o.startswith("⠴")


def test_줄머리라도_마침표가_없으면_로마자표형():
    """gold p0002 1행은 'IV 유전'을 ⠴⠠⠠⠊⠧⠲ 로 적는다 — 공백은 섹션번호 신호가 아니다."""
    assert T("Ⅳ 유전").startswith("⠴⠠⠠⠊⠧⠲")
