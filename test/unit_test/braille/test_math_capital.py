"""수식 구역 대문자표 — 「수학 점자」 제12항 · 「한글 점자」 제28항 [붙임].

`⠠`(대문자 기호표)·`⠠⠠`(대문자 단어표)가 수식 경로에서 빈 문자열로 빠져
뒤 글자가 소문자로 나갔다 — `\\frac{1}{AB}` → `(ab)분의1` · `P(X)` → `p(x)`.
"""
import pytest

from app.utils.braille_back import decode


@pytest.mark.parametrize("raw,want", [
    ("⠷⠠⠁⠠⠃⠾⠌⠼⠁", "(AB)분의1"),        # 제12항 3호 예시 `,A,B`
    ("⠠⠏⠦⠠⠭⠴⠒⠒⠼⠁", "P(X)=1"),          # 확률 P(X)
    ("⠠⠉⠷⠼⠉⠀⠼⠃⠾", "C(3 2)"),            # 조합 ₃C₂ (제62항 3호, 확통 p0022 실물)
    ("⠈⠉⠠⠠⠁⠙⠒⠒⠼⠁", "̅AD=1"),           # 선분 + 대문자 단어표 (제35항 [붙임])
])
def test_수식_대문자표를_살린다(raw, want):
    assert decode(raw) == want


def test_한글_초성_ㅅ은_대문자표가_아니다():
    """`⠠⠥` 는 `소` 다 — 뒤가 통째로 한글로 풀리면 대문자로 올리지 않는다."""
    assert decode("⠠⠥⠈⠪⠢⠑⠯⠮") == "소금물을"      # 생명과학 I p0088 실물
