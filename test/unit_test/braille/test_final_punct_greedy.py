"""한 칸 문장 부호가 앞 음절 받침으로 먹히던 것 (2026-09-04).

`⠲`=받침 ㅍ · `⠖`=받침 ㅋ · `⠦`=받침 ㅌ 이라(규정 제3항) 탐욕 매칭이 부호를
앞 음절에 붙여 먹었다. 반대로 진짜 받침을 부호로 읽던 자리(`읊고`→`을.고`)도
같은 판정의 뒷면이라 함께 본다.
"""
from app.utils.braille_back import decode


def test_어말_온점이_받침ㅍ으로_먹히지_않는다():
    assert decode("⠕⠌⠎⠲") == "있어."            # 있엎
    assert decode("⠘⠂⠁⠚⠱⠜⠨⠕⠲") == "밝혀야지."   # 밝혀야짚


def test_어말에_서는_받침ㅍ_음절은_그대로_둔다():
    assert decode("⠣⠲⠪⠐⠥") == "앞으로"
    assert decode("⠠⠍⠲⠀⠠⠭") == "숲 속"
    assert decode("⠑⠍⠐⠪⠲") == "무릎"
    assert decode("⠉⠥⠲⠊⠣") == "높다"


def test_받침ㅍ을_온점으로_잘못_읽지_않는다():
    assert decode("⠮⠲⠈⠥") == "읊고"             # 을.고


def test_여는_괄호_대괄호가_받침ㅌ으로_먹히지_않는다():
    assert decode("⠈⠍⠰⠝⠦⠄") == "구체("          # 구쳍'
    assert decode("⠈⠕⠂⠦⠆⠊⠥⠰⠴") == "길[도]"     # 긽;도]


def test_받침ㅌ_음절_뒤의_여는_괄호는_둘_다_산다():
    assert decode("⠘⠦⠦⠄⠈⠍⠐⠪⠢⠠⠴") == "밭(구름)"
    assert decode("⠠⠈⠪⠦⠦⠄") == "끝("


def test_닫는_부호_앞_느낌표가_받침ㅋ으로_먹히지_않는다():
    assert decode("⠊⠣⠖⠴") == "다!”"             # 닼”


# ── 반대 방향: 진짜 받침을 부호로 읽던 것 (2026-09-09) ──────────────────────────
# 위 파일이 처음부터 `⠲`=받침 ㅍ · `⠖`=받침 ㅋ · `⠦`=받침 ㅌ 셋을 다 적어 놨는데,
# **반대 방향(진짜 받침을 부호로 읽는 쪽)은 ㅍ 하나만** 봤다(`읊고`). 그래서 어말
# ㅌ·ㅋ 이 통째로 새는 것을 아무도 못 잡았다 — 대표가 보고서 실물에서 찾았다.
def test_어말_받침ㅌ을_물음표로_읽지_않는다():
    assert decode("⠘⠠⠫⠦") == "바깥"          # 바까?
    assert decode("⠠⠈⠪⠦") == "끝"            # 끄?
    assert decode("⠑⠕⠦") == "밑"             # 미?
    assert decode("⠘⠦") == "밭"              # 바?
    assert decode("⠙⠦") == "팥"              # 파?
    assert decode("⠠⠍⠦") == "숱"             # 수?


def test_어말_받침ㅋ을_느낌표로_읽지_않는다():
    assert decode("⠘⠍⠎⠖") == "부엌"          # 부어!
    assert decode("⠊⠿⠉⠱⠖") == "동녘"         # 동녀!


def test_진짜_물음표_느낌표는_그대로_둔다():
    # 받침 ㅌ 목록에 넣은 음절은 민 음절 + `?` 와 겹치지 않는 것만 골랐다
    # (재추출 묵자 1,361쪽 실측 — `끄?`·`바?`·`미?`·`수?`·`파?` 0회).
    assert decode("⠎⠠⠊⠞⠠⠫⠦") == "어떨까?"
    assert decode("⠈⠪⠐⠾⠫⠦") == "그런가?"
    assert decode("⠧⠗⠦") == "왜?"
    assert decode("⠨⠻⠑⠂⠖") == "정말!"


# ── 닫는 부호 앞 물음표 · 줄 끝에 남은 어간 (2026-09-10) ────────────────────────
# 위 두 방향을 한 번씩 봤는데도 **닫는 부호 앞**은 느낌표(⠖)만 봤다(`다!”`). 물음표
# ⠦ 쪽은 그대로 남아, 인용문이 통째로 깨졌다 — 전 코퍼스 1,251쪽에 44건.
# 반대쪽(줄 끝에 남은 어간)도 명사만 봐서 `달라붙/는다` 가 `달라부?` 로 나갔다.
def test_닫는_부호_앞_물음표가_받침ㅌ으로_먹히지_않는다():
    assert decode("⠞⠑⠉⠜⠦⠴") == "얼마냐?”"          # 얼마냩”
    assert decode("⠉⠀⠑⠂⠕⠥⠦⠴") == "나 말이오?”"     # 나 말이옽”
    assert decode("⠉⠍⠈⠯⠠⠫⠦⠴⠄") == "누굴까?’"      # 누굴깥’


def test_줄_끝에_남은_어간의_받침ㅌ을_물음표로_읽지_않는다():
    assert decode("⠊⠂⠐⠣⠘⠍⠦") == "달라붙"           # 달라부?
    assert decode("⠙⠬⠑⠡⠐⠀⠈⠎⠦") == "표면, 겉"      # 표면, 거?


def test_받침ㅌ_음절은_닫는_부호_앞에서도_받침으로_남는다():
    assert decode("⠘⠠⠫⠦⠴") == "바깥”"
    assert decode("⠠⠈⠪⠦⠴⠄") == "끝’"
    assert decode("⠘⠥⠢⠘⠱⠦⠴⠄") == "봄볕’"


def test_목록에_없는_음절은_물음표로_읽는다():
    # `맡`·`샅` 은 묵자에 `마?`·`사?` 가 0회라 안전해 보였지만, 영어 지문이 한글로
    # 새는 쪽에서 영어 물음표를 먹어(개선 1 : 악화 13) 일부러 뺐다.
    assert decode("⠈⠞⠀⠇⠦") == "걸 사?"             # 걸 샅 (이태준 「돌다리」)
