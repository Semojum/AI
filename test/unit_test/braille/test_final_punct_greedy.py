"""한 칸 문장 부호가 앞 음절 받침으로 먹히던 것 (2026-09-04).

`⠲`=받침 ㅍ · `⠖`=받침 ㅋ · `⠦`=받침 ㅌ 이라(규정 제3항) 탐욕 매칭이 부호를
앞 음절에 붙여 먹었다. 반대로 진짜 받침을 부호로 읽던 자리(`읊고`→`을.고`)도
같은 판정의 뒷면이라 함께 본다.
"""
from app.utils.braille_back import decode


def test_어말_온점이_받침ㅍ으로_먹히지_않는다():
    assert decode("⠕⠌⠎⠲") == "있어."            # 있엎
    assert decode("⠘⠂⠁⠚⠱⠜⠨⠕⠲") == "밝혀야지."   # 밝혀야짚


def test_어말에_서는_받침ㅍ_음절은_그대로_둔다():
    assert decode("⠣⠲⠪⠐⠥") == "앞으로"
    assert decode("⠠⠍⠲⠀⠠⠭") == "숲 속"
    assert decode("⠑⠍⠐⠪⠲") == "무릎"
    assert decode("⠉⠥⠲⠊⠣") == "높다"


def test_받침ㅍ을_온점으로_잘못_읽지_않는다():
    assert decode("⠮⠲⠈⠥") == "읊고"             # 을.고


def test_여는_괄호_대괄호가_받침ㅌ으로_먹히지_않는다():
    assert decode("⠈⠍⠰⠝⠦⠄") == "구체("          # 구쳍'
    assert decode("⠈⠕⠂⠦⠆⠊⠥⠰⠴") == "길[도]"     # 긽;도]


def test_받침ㅌ_음절_뒤의_여는_괄호는_둘_다_산다():
    assert decode("⠘⠦⠦⠄⠈⠍⠐⠪⠢⠠⠴") == "밭(구름)"
    assert decode("⠠⠈⠪⠦⠦⠄") == "끝("


def test_닫는_부호_앞_느낌표가_받침ㅋ으로_먹히지_않는다():
    assert decode("⠊⠣⠖⠴") == "다!”"             # 닼”
