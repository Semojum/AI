"""수식 경계의 두 칸은 점자 조판이라 묵자로 내보내지 않는다 (「수학 점자」 제11항).

제11항 "수식과 수학적 표기는 앞뒤를 두 칸씩 띄어 쓴다" 는 **점자에만** 넣으라는 칸이다.
역점역이 칸을 1:1로 옮겨 묵자에 없던 공백이 샜다 — `2^40 은 몇 …`.

접는 폭은 재추출 묵자 1,361쪽 실측에서 왔다(추측이 아니다):
    수식 뒤 → 한글  붙임 14,101 (90.7%) · 한 칸 1,446
    한글 뒤 → 수식  한 칸 13,119 (99.6%) · 붙임 42

가드: 표 조판도 열 항목을 두 칸으로 가른다(「점자 자료 제작 지침」 2075·2121행).
한쪽이라도 수식일 때만 접으므로 한글→한글 두 칸(전권 77,175곳)은 안 건드린다.
"""
import pytest

from app.utils.braille_ascii import ascii_to_unicode
from app.utils.braille_back import decode


def _dec(brf: str) -> str:
    """규정 원문 BRF — 백틱이 공백이다(코퍼스와 반대)."""
    return decode(ascii_to_unicode(brf, backtick="space")).strip()


def test_규정_제11항_예문이_묵자_그대로_돌아온다():
    """규정 원문 묵자가 `2⁴⁰은 몇 자리 정수인가?` 다 — 두 칸이 남으면 `2^40 은` 이 된다."""
    assert _dec("``#b^#dj``z`e:2`.\"o`.],mq$8") == "2^40은 몇 자리 정수인가?"


def test_한글_뒤_수식은_한_칸이다():
    """제12항 1호 예문. 앞쪽 두 칸은 낱말 사이 한 칸으로 줄인다(묵자 99.6%)."""
    assert _dec("``o`^7.],oaw`jrcz``x33#a``oi4").endswith("해는 x=1이다.")


def test_과학_제6항_국어_문장_안_식():
    """규정 원문 묵자가 `… C + O_2 → CO_2이다.` 다 — 식 뒤 두 칸이 붙어야 한다."""
    assert _dec("``,c`5`,o;#b`>3`,c,o;#b``oi4").endswith("CO_2이다.")


@pytest.mark.parametrize("brf", [
    "⠛⠣⠀⠀⠕⠌⠊",          # 한글 → 한글 (표 열 항목)
    "⠛⠣⠀⠀⠕⠌⠊⠀⠀⠛⠣",     # 표 행 꼴
])
def test_한글_사이_두_칸은_표라서_안_건드린다(brf):
    """열 항목을 가르는 두 칸(제작 지침 2075·2121행)은 그대로 둔다."""
    assert "  " in decode(brf)


@pytest.mark.parametrize("brl,keep", [
    # 표의 빈칸 열이 `-` 한 칸이다. 붙이면 앞 수식과 한 낱말이 되어 감쌈 붙임표 복원이
    # `-0.34375-` 를 `(0.34375)` 로 바꿔 버린다. 전권 전수 대조에서 걸린 자리다.
    ("⠀⠀⠼⠉⠐⠂⠀⠼⠙⠌⠼⠉⠀⠀⠔⠼⠚⠲⠉⠙⠉⠛⠑⠀⠀⠔", "-0.34375  -"),
    ("⠔⠼⠁⠚⠈⠔⠔⠼⠑⠴⠙⠠⠉⠀⠀⠤⠀⠀⠼⠓⠚⠁⠴⠙⠠⠉⠀⠀", "  -  "),
])
def test_뒤가_한글이_아니면_안_붙인다(brl, keep):
    """제11항은 수식 뒤에 **한글**이 올 때다 — 홑 기호 토큰은 조판 칸이라 남긴다."""
    assert keep in decode(brl)


def test_줄머리_들여쓰기는_그대로다():
    """줄 가장자리의 칸은 조판 들여쓰기다 — 토큰 사이가 아니라 안 접는다."""
    assert decode("⠀⠀⠛⠣").startswith("  ")
