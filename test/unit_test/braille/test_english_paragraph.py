"""로마자표 없는 영문 문단과 대문자표 — 제29항 [다만] · 제32항.

이 파일이 지키는 것 둘.

1. **대문자표 ⠠ 가 약자 앞에서 사라지지 않는다.** 통일영어점자는 낱말을 약자로 줄이는데
   (제32항), 종전 코드는 ⠠ **다음 셀이 낱자일 때만** 대문자로 만들고 약자 앞에서는 표를
   통째로 버렸다. `,:5`(When) 가 `when` 으로, `,/RUCTURE`(Structure) 가 `structure` 로
   나갔다. 전 코퍼스 18,892쪽에서 이 한 가지로 **4,839줄**의 첫 글자가 바뀐다.

2. **로마자표가 없는 영문 문단을 영어로 읽는다.** 제29항 [다만]은 문단 전체가 로마자일
   때 로마자표·종료표를 생략하게 한다. 종전 판정은 정방향 `eng_braille` 로 되짚어
   **완전히 같을 때만** 영어로 봤는데, 정방향은 숫자를 점자로 바꾸지 않고(`1940s`)
   낱말표도 도서와 다르게 써서(`to` → ⠖, 도서는 ⠞⠕) 영어 지문 줄은 옳게 읽어도 왕복을
   통과하지 못했다. 영어 교재 한 쪽이 통째로 뜻 없는 한글로 나가던 뿌리다.

**순환검증 금지**: 왕복 대신 쓰는 증거(**서로 다른** 기능어 둘)는 전 코퍼스 실측으로
갈랐다. 개수 기준이면 영어책 밖에서 81줄이 뒤집히고 그중 20줄이 한글 손해인데, 서로
다른 둘을 요구하면 손해가 7줄로 줄고 이득은 11,616 → 11,323줄만 준다.
"""
from __future__ import annotations

import pytest

from app.utils.braille_back import decode


@pytest.mark.parametrize("cells, expected", [
    # ⠠ + 약자 — 종전에는 대문자표가 버려졌다
    ("⠴⠠⠱⠢⠲", "When"),                    # ,:5 · ⠱=wh ⠢=en
    ("⠴⠠⠌⠗⠥⠉⠞⠥⠗⠑⠲", "Structure"),        # ,/RUCTURE · ⠌=st
    ("⠴⠠⠸⠮⠲", "Their"),                   # ,_! · ⠸⠮ 두 칸 약자
    # ⠠ + 낱자는 종전대로
    ("⠴⠠⠋⠕⠉⠥⠎⠲", "Focus"),
])
def test_대문자표는_약자_앞에서도_산다(cells, expected):
    assert decode(cells) == expected


def test_로마자표_없는_영문_줄을_영어로_읽는다():
    """`late 1940s, a neighbor used to` — 숫자·쉼표가 있어 왕복이 못 맞던 줄."""
    cells = "⠇⠁⠞⠑⠀⠼⠁⠊⠙⠚⠎⠂⠀⠁⠀⠝⠑⠊⠣⠃⠕⠗⠀⠥⠎⠫⠀⠞⠕"
    assert decode(cells) == "late 1940s, a neighbor used to"


def test_기능어가_되풀이만_되면_영어로_안_본다():
    """자모 보기 `ㄴ ㄷ ㄹ` 은 ⠿(온표)가 되풀이돼 `for … for` 로 읽힌다.

    기능어를 **개수**로 세면 통과하므로 **서로 다른** 둘을 요구한다. 이 줄이 뒤집히면
    세계지리 보기 항목이 통째로 깨진다(전 코퍼스 실측 8줄).
    """
    assert "for" not in decode("⠀⠀⠠⠃⠇⠑⠆⠀⠿⠒⠀⠿⠔⠝⠀⠿⠂")


def test_낱말_중간_대문자표는_영어가_아니다():
    """한글 오탐 `⠁⠉ ⠚⠻⠙⠻ ⠛⠊⠿⠕ ⠚⠧⠁⠇⠒⠊⠽⠑⠡⠠⠎ ⠕⠝` 이 그 꼴이었다.

    기능어 둘(according · on)이 있어 그것만으로는 못 거른다. 낱말 **중간**의 대문자표는
    영어 표기에 거의 없다는 것으로 가른다.
    """
    got = decode("⠀⠀⠁⠉⠀⠚⠻⠙⠻⠀⠛⠊⠿⠕⠀⠚⠧⠁⠇⠒⠊⠽⠑⠡⠠⠎⠀⠕⠝")
    assert "그러나" in got


def test_아포스트로피_축약을_읽는다():
    """`don't seek employment with the company.` — ⠄ 하나에 줄 전체가 막혔다.

    아포스트로피는 3점 ⠄ 한 칸이다(EBAE·UEB 공통, 점역사 회신 A13). 로마자 런의 글자가
    아니라 `_decode_roman_run` 이 낱말을 끝까지 못 읽고 멈추고, 그러면 줄 판정이 통째로
    무너져 `피엣얼 어마맞 무워사이외철 …` 이 나갔다.
    전 코퍼스 18,892쪽 실측: 이것 하나로 1,044줄이 영어로 읽히고 잃는 줄은 0이다.
    """
    cells = "⠙⠕⠝⠄⠞⠀⠎⠑⠑⠅⠀⠑⠍⠏⠇⠕⠽⠰⠞⠀⠾⠀⠮⠀⠉⠕⠍⠏⠁⠝⠽⠲"
    assert decode(cells) == "don't seek employment with the company."


def test_아포스트로피_꼬리는_닫힌_집합이다():
    """한글 줄의 ⠄ 를 로마자가 삼키면 안 된다.

    ⠄ 는 한글 쪽에서 여는 소괄호 `⠦⠄`·닫는 작은따옴표 `⠴⠄` 의 뒷칸이기도 하다. 꼬리를
    일곱 종(`'s 't 'd 'm 're 've 'll`)으로 못 박아 두는 이유가 이것이다.
    """
    got = decode("⠘⠎⠄⠎⠉⠌⠈⠥⠐⠀⠕⠐⠮⠀⠓⠗⠨⠻⠈⠧⠒⠕⠀⠰⠎⠐⠕⠚⠉⠵")
    assert got == "벗어났고, 이를 태정관이 처리하는"
