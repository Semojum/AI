"""유전자형 표기의 역점역 — 「과학 점자」 제23항 + 「수학 점자」 제18항 1호.

제18항 1호가 "지수는 위첨자 기호 ^을 적고, 첨자를 구성하는 수, **문자** 또는 수식을
적는다"라 하고 예문이 `aᵏ` = `a^k` 다. 제23항이 대문자 유전자를 1급 점자로 적으므로
`X^A` = ⠠⠭⠘⠠⠁ 가 된다. 수식 판정은 첨자 **뒤에 수표 ⠼** 가 와야 신호로 보므로 낱자
첨자를 못 잡았고, 그래서 이 꼴이 통째로 한글로 읽혔다 — `속바a` · `쏙바b옥밥`.

⚠ 게이트가 좁아야 한다. ⠠ 는 된소리표이고 ⠘ 는 한글 `바` 다. 아래 두 번째 클래스가
  그 경계를 지킨다 — 넓히면 `신바시에서`·`속보로`가 깨진다.
"""
from __future__ import annotations

import pytest

from app.utils.braille_back import decode


class Test유전자형을_편다:
    @pytest.mark.parametrize("cells, want", [
        ("⠠⠭⠘⠠⠁", "X^A"),                       # 대문자표 + 위첨자 대문자
        ("⠠⠠⠭⠘⠠⠁⠽", "X^AY"),                    # 대문자 단어표 — 꼬리 낱자도 대문자
        ("⠠⠭⠘⠠⠁⠠⠽", "X^AY"),                    # 꼬리에 대문자표가 따로 붙은 꼴
        ("⠠⠠⠭⠘⠠⠁⠭⠘⠁", "X^AX^a"),                # 위첨자는 자기 대문자표로 갈린다
        ("⠠⠠⠭⠘⠠⠁⠭⠘⠠⠁", "X^AX^A"),
        ("⠠⠠⠭⠘⠠⠓⠭⠘⠓", "X^HX^h"),
        ("⠠⠊⠘⠠⠁⠠⠊⠘⠠⠃", "I^AI^B"),               # 혈액형 대립유전자
        ("⠠⠊⠘⠠⠁⠊", "I^Ai"),
    ])
    def test_점형이_묵자로_돌아온다(self, cells, want):
        assert decode(cells) == want


class Test한글을_먹지_않는다:
    """게이트를 넓히면 무너지는 자리. 전권 18,892쪽 실측에서 뽑았다."""

    @pytest.mark.parametrize("cells, want", [
        ("⠠⠟⠘⠠⠕⠝⠠⠎", "신바시에서"),   # 런 뒤에 낱자가 더 이어진다 → 유전자형이 아니다
        ("⠠⠥⠘⠕", "소비"),              # ⠠[낱자]⠘ 만으로는 신호가 아니다 (전권 420회)
        ("⠠⠍⠘⠁⠁⠝", "수밖에"),          # 336회
        ("⠠⠎⠘⠕⠠⠪", "서비스"),          # 235회 — 뒤에 ⠠ 가 나와도 게이트 밖이다
        ("⠠⠾⠘⠛", "선분"),
    ])
    def test_한글이_그대로_남는다(self, cells, want):
        assert decode(cells) == want
