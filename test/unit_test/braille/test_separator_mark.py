"""구분표 ⠤ 가 붙임표처럼 본문에 남던 것 (규정 제11·12항).

제11항 모음자 + '예', 제12항 'ㅑ·ㅘ·ㅜ·ㅝ' + '애' 사이의 ⠤ 는 **묵자에 없는 읽기
보조표**다. 묵자 대조(재추출 1,180쪽): 규정형 79건 전부 붙임표 없음 · 있음 0건.

★ 그냥 지우면 안 된다 — 구분표는 토큰 경계이기도 해서 뒤 셀이 앞 음절 받침으로
  먹힌다(아예 → `았`, 인의예지 → `인읬지`, 수액 → `쉭`). 끊어 읽어야 한다.
"""
import pytest

from app.utils.braille_back import decode


@pytest.mark.parametrize("cells,expect", [
    ("⠣⠤⠌", "아예"),          # 규정 제11항 예시 `<-/`
    ("⠠⠎⠤⠌", "서예"),         # 규정 제11항 예시 `,s-/`
    ("⠠⠍⠤⠗⠁", "수액"),        # 규정 제12항 예시 `,m-ra`
    ("⠠⠥⠚⠧⠤⠗⠁", "소화액"),    # 규정 제12항 예시 `,ujv-ra`
    ("⠟⠺⠤⠌⠨⠕", "인의예지"),   # 결함 H 원 표본 (윤리와 사상 p0018)
    ("⠇⠑⠤⠌⠝⠈⠝", "사마예에게"),  # 약자 '마' + 예 (동아시아사 p0022, 묵자 대조 완료)
])
def test_구분표를_떼고_끊어_읽는다(cells, expect):
    assert decode(cells) == expect


def test_규정_밖은_안_건드린다():
    # ㅔ + 애 는 제12항(ㅑㅘㅜㅝ)이 아니다 — 묵자에 진짜 붙임표가 있는 자리다(전권 21건).
    assert decode("⠈⠥⠰⠝⠤⠗⠁⠰⠝") == "고체-액체"


def test_감쌈_붙임표는_저쪽_규칙에_넘긴다():
    # ⠤예⠤ 는 도서 관행 `(예)` 다(_restore_wrap_parens). 앞뒤 3셀 안의 ⠤ 를 보고 비켜난다.
    assert decode("⠊⠮⠐⠕⠠⠕⠠⠥⠤⠌⠤⠲") == "들리시소(예)."
