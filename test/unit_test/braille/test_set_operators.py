"""집합 연산 ∩·∪ — 「수학 점자」 제61항 5 (2026-09-07).

규정이 합집합 ∪ 를 `+`(⠬), 교집합 ∩ 를 `%`(⠩)로 적되 **앞뒤를 한 칸씩 띄우라** 한다.
그래서 홑 셀이 토큰 하나로 서는데 그 점형이 한글 약자 `요`·`유` 와 같아 그대로 나갔다.

★ 2026-09-06 아침에 "한글과 겹쳐 불가" 로 한 번 기각한 자리다. 그때는 **양옆을 안 봤다.**
  양옆이 집합 이름(대문자표+낱자)일 때만 보면 전권 274회가 전부 수식이고 한글이 0건이다.
  이 테스트가 그 가드를 지킨다 — 아래 한글 케이스가 깨지면 가드가 풀린 것이다.
"""
import pytest
from app.utils.braille_back import decode


@pytest.mark.parametrize("raw,want", [
    ("⠠⠏⠦⠠⠁⠀⠩⠀⠠⠃⠴⠒⠒", "쉍a∩B)="),
    ("⠝⠦⠠⠁⠀⠬⠀⠠⠃⠴⠒⠒⠼⠑", "엩a∪B)=5"),
])
def test_집합연산은_양옆이_집합이름일때만(raw, want):
    assert decode(raw).strip() == want


@pytest.mark.parametrize("raw", [
    "⠕⠀⠩⠀⠘⠁⠕⠣⠮",          # `유 부인을` — 유씨 성
    "⠕⠀⠬⠀⠨⠕⠐⠕⠨⠹",          # `요 지리적`
])
def test_양옆이_집합이름이_아니면_한글로_남는다(raw):
    d = decode(raw)
    assert "∩" not in d and "∪" not in d, d
