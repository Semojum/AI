"""연산 기호 앞뒤 한 칸 — 「수학 점자」 제15항 · 제61항 5 (2026-09-07).

규정이 집합 연산 ∩·∪ 를 `%`·`+`, 일반연산 ⊕⊖⊗∗∘⦾ 를 `_5`·`_9`·`_*`·`_<`·`_0`·`_00`
로 적되 **기호의 앞뒤를 한 칸씩 띄어 쓰라** 한다(제15항, 재추출본 3485행).
묵자는 붙여 쓰므로(`x⊕y`, 3487행) 역방향에서는 그 두 칸을 지워야 한다.

★ 그 칸이 토큰을 셋으로 쪼개는 바람에 **양옆이 문맥을 잃어 한글로 떨어졌다** —
  `x ⊕ y` 가 `옥 ⊕ y`, `P(A ∩ B)=` 가 `쉍a∩B)=` 로 나갔다. 연산자가 서면 양옆은
  피연산자이므로 수식으로 읽는다.

★ 2026-09-06 아침에 "한글과 겹쳐 불가" 로 한 번 기각한 자리다. 그때는 **양옆을 안 봤다.**
  아래 한글 케이스가 그 가드를 지킨다 — 깨지면 가드가 풀린 것이다.
"""
import pytest
from app.utils.braille_back import decode


@pytest.mark.parametrize("raw,want", [
    # 제61항 5 — 양옆이 집합 이름일 때만
    ("⠠⠏⠦⠠⠁⠀⠩⠀⠠⠃⠴⠒⠒", "P(A∩B)="),
    ("⠝⠦⠠⠁⠀⠬⠀⠠⠃⠴⠒⠒⠼⠑", "n(A∪B)=5"),
    # 제15항 1~6호 — 규정 예문 그대로(3487·3490·3493·3499행)
    ("⠭⠀⠸⠢⠀⠽⠒⠒⠼⠃⠭⠢⠼⠉⠽", "x⊕y=2x+3y"),
    ("⠁⠀⠸⠔⠀⠃⠒⠒⠼⠉⠦⠁⠢⠃⠴", "a⊖b=3(a+b)"),
    ("⠭⠀⠸⠡⠀⠽⠒⠒⠭⠘⠼⠉⠢⠽", "x⊗y=x^3+y"),
    ("⠁⠀⠸⠴⠀⠑⠒⠒⠁⠑⠢⠁", "a∘e=ae+a"),
])
def test_연산기호_앞뒤_한_칸을_지운다(raw, want):
    assert decode(raw).strip() == want


@pytest.mark.parametrize("raw", [
    "⠕⠀⠩⠀⠘⠁⠕⠣⠮",          # `유` — 유씨 성
    "⠕⠀⠬⠀⠨⠕⠐⠕⠨⠹",          # `요 지리적`
])
def test_양옆이_집합이름이_아니면_한글로_남는다(raw):
    d = decode(raw)
    assert "∩" not in d and "∪" not in d, d


@pytest.mark.parametrize("raw,no", [
    # 전권 실측에서 나온 본문 자리 — 양옆이 피연산자가 아니라 그대로 둔다
    ("⠠⠛⠕⠎⠌⠊⠲⠀⠸⠔⠀⠊⠶⠐⠩⠐⠂", "순이었다.⊖"),
    ("⠈⠕⠚⠥⠀⠸⠴⠀⠺", "기호∘의"),
])
def test_양옆이_본문이면_붙이지_않는다(raw, no):
    assert no not in decode(raw), decode(raw)


@pytest.mark.parametrize("raw,want", [
    # 전권 전수 대조에서 되물린 자리 — 집합 이름 가드는 통과해도 양옆이 본문이다.
    # 양옆을 수식으로 켜면 `(;O각자·요_)∪유·아시아` · `또 X이려구,∪자Oa!)` 로 깨졌다.
    ("⠀⠀⠦⠆⠠⠕⠫⠁⠨⠐⠬⠰⠴⠀⠬⠀⠩⠐⠣⠠⠕⠣⠀⠊⠗⠐⠩⠁⠀", "[시각자료]∪유라시아 대륙"),
    ("⠊⠮⠎⠌⠊⠲⠀⠠⠊⠥⠀⠠⠭⠕⠐⠱⠈⠍⠐⠀⠬⠀⠨⠠⠕⠁⠖⠴", "들었다. 또 속이려구,∪자식!”"),
    # 양옆이 기호라 피연산자가 아니다(화학식 `F + e^- → F^-`, MS-REF-T26-015 p0067)
    ("⠀⠀⠼⠢⠀⠠⠋⠀⠢⠀⠸⠔⠀⠒⠕⠀⠠⠋⠘⠔", "⑤ 카 + ⊖ → 카받"),
    # 점역자주표를 단 토큰은 피연산자가 아니다(점자 부호표, MS-TXT-K2630 p0059)
    ("⠈⠣⠀⠀⠇⠠⠄⠀⠀⠸⠡⠀⠀⠇⠀⠀⠸⠳", "'아  사【점역자주】  \\  사  |"),
])
def test_양옆이_본문이면_수식으로_켜지_않는다(raw, want):
    assert decode(raw).strip() == want
