"""단독 문장 부호(제49항 [붙임])와 로그(「수학 점자」 제46항) 역맵 회귀 가드.

이 파일이 지키는 것: ⠸ 로 시작하는 두 꼴이 미지셀 ⟨2838⟩ 로 새지 않는 것.
정방향은 둘 다 이미 낸다 — 역맵에만 없었다.

**순환검증 금지**: 기대값 출처는 규정과 정답 도서다.
  · 제49항 [붙임] — "빈칸 뒤에 문장 부호가 단독으로 쓰여 다른 기호와 혼동될 때에는
    그 앞에 _ 을 적고…"(규정_텍스트.txt 2314행). 예문 `? 대신 .를 쓸 수 있다.`
  · 「수학 점자」 제46항 로그. 정답 도서 009 p0006 gold `\\log 2 = 0.3010` 자리의
    점자가 `⠸⠼⠃⠒⠒…` 인데 우리는 `⟨2838⟩2=0.3010` 으로 냈다.

★ **범위를 좁힌 근거**(실측, 네모 문자 쌍을 걷어 낸 뒤 전 코퍼스):
    ⠸⠦ 207회·76쪽 → 단독 물음표로 편다
    ⠸⠼  78회· 9쪽(전부 수학I) → 로그로 편다
  ⠸ 뒤의 다른 부호 셀은 이미 다른 뜻이 있어 **안 건드린다** —
    ⠸⠲ ▲ 글머리 31,629회 · ⠸⠌ 빗금 14,635회 · ⠸⠤ 밑줄 5,159회.
  홑 ⠸ 를 로그로 두는 안은 **기각 이력**이 있다(코퍼스 전수 105,453자 유출).
"""
from __future__ import annotations

import pytest

from app.utils.braille_back import decode


def test_짝없는_물음표는_단독_물음표다():
    assert decode("⠫⠀⠸⠦") == "가 ?"


def test_뒤에_글자가_붙으면_물음표가_아니다():
    """줄을 넘는 네모 문자의 여는 쪽이다 — 닫는 ⠴⠇ 가 다음 줄에 있어 짝이 안 잡힌다.

    규정 제49항 [붙임]은 단독 부호 **뒤에 한 칸을 띄라**고 정한다. 그 자리만 편다.
    실측: 짝 없는 ⠸⠦ 207회 중 빈칸·줄끝 앞이 105회다. 구분을 안 하면
    `⠸⠦조직 세포` 가 `?조직 세포` 로 깨진다(001 p0031).
    """
    assert "?" not in decode("⠸⠦⠨⠕⠨⠄")


def test_네모_문자가_먼저다():
    """`⠸⠦ … ⠴⠇` 는 네모 문자(제64항)다 — 단독 물음표로 먹으면 안 된다."""
    assert decode("⠸⠦⠈⠣⠴⠇").startswith("▯")


@pytest.mark.parametrize("cells, expected", [
    ("⠸⠼⠃", "log 2"),
])
def test_수표_앞_ㅅ자리는_로그다(cells, expected):
    assert decode(cells, math=True) == expected
    assert decode(cells) == expected          # 본문 경로도 같다


def test_도형_틀은_그대로다():
    """⠸ 를 건드렸으니 도형 반복 틀(제57·58항)이 안 깨지는지 같이 본다."""
    assert decode("⠸⠶⠶⠇") == "□□"
    assert decode("⠸⠴⠴⠇") == "○○"
