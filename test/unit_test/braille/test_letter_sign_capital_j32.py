"""제32항 — 문자표 ⠰ 뒤 대문자표 ⠠ + 낱자는 홑 대문자다 (2026-09-06).

규정 제32항(재추출본 1650행): "로마자표와 로마자 종료표 사이의 표기는 「통일영어점자
규정」에 따라 적는다." 통일영어점자는 홑 낱자가 낱말표로 읽히지 않게 문자표 ⠰ 를
앞세우고, 대문자면 그 뒤에 대문자표 ⠠ 를 더 붙인다. 규정 예문이 그 꼴을 직접 쓴다 —
3349행 `세 점 A, B, C가 있다.` = ``,n`.s5`0,a1`;,b1`;,c4$`o/i4`` (`;,b` = ⠰⠠⠃ = B).

#532 가 소문자(⠰+낱자)를 넣었는데 대문자 꼴은 로마자표 ⠴ 로 열린 런 안에서만 읽혀,
런 밖에서는 ⠰ 가 밑줄로 새고 ⠠+낱자가 한글로 풀렸다 — `(B)` 가 `라_b랴` 로 나갔다.

★ 가드 둘을 같이 박는다.
  ① 앞이 낱자면 제68항 **아래첨자표**다(`m_A`). 먹으면 수식이 깨진다.
  ② 뒤에 낱자가 더 오면 문자표가 아니다 — 문자표는 홑 낱자용이다.
★ 바깥 소괄호 ⠐⠣ ⠐⠜ 는 원장 R-34 로 기각이라 `라…랴` 로 남는다(한글 `라` 와 같은 셀).
★ 규정 예문의 기댓값에 남은 `C.`·`V.` 의 마침표는 **종료표 ⠲ 를 마침표로 읽는 것**이라
  이 축이 아니다(제33항 [다만] · 별도 회차). 여기서는 낱자가 대문자로 나오는지만 본다.
"""
from __future__ import annotations

import pytest

from app.utils.braille_back import decode


@pytest.mark.parametrize("cells, want", [
    # 규정 3349행 — 세 점 A, B, C가 있다.
    ("⠠⠝⠀⠨⠎⠢⠀⠴⠠⠁⠂⠀⠰⠠⠃⠂⠀⠰⠠⠉⠲⠫⠀⠕⠌⠊⠲", "세 점 A, B, C.가 있다."),
    # 규정 1792행 — George V
    ("⠴⠠⠛⠑⠕⠗⠛⠑⠀⠰⠠⠧⠲⠱⠌⠊⠲", "George V.였다."),
    # 실물 — 영어 교재 선택지 (B). 바깥 괄호는 R-34 기각이라 `라…랴` 로 남는다.
    ("⠐⠣⠰⠠⠃⠐⠜", "라B랴"),
    # 실물 — 듣기 대본 화자 표시 M
    ("⠰⠠⠍⠒", "M="),
    # 실물 — 글상자 안 홑 대문자 V
    ("⠸⠦⠰⠠⠧⠴⠇", "▯V▯"),
])
def test_letter_sign_capital_reads_as_capital(cells, want):
    assert decode(cells).strip() == want


@pytest.mark.parametrize("cells, want", [
    # ① 앞이 낱자 → 제68항 아래첨자다. 문자표로 먹으면 안 된다.
    ("⠍⠰⠠⠁⠧⠰⠠⠁⠢⠍⠰⠠⠃⠧⠰⠠⠃⠒⠒", "m_Av_A+m_Bv_B="),
    # ② 뒤에 낱자가 더 오면 문자표가 아니다 — 로마자 런이 그대로 읽는다.
    ("⠴⠰⠠⠁⠃⠲⠧", "About와"),
])
def test_subscript_and_multiletter_are_untouched(cells, want):
    assert decode(cells).strip() == want
