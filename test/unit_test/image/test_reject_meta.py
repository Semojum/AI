"""캡셔너 메타 응답 차단 회귀.

모델이 그림을 묘사하는 대신 **사용자에게 말을 거는** 응답을 낼 때가 있다. 그게 그대로
점역자 주로 나가면 시각장애 학생이 손으로 "파일을 첨부해 주세요"를 읽는다. 빈 캡션보다
나쁘다 — 빈 캡션은 CAPTION_FAILED 플래그로 드러나지만 이건 정상 캡션인 척한다.

넓힐 때 지켜야 할 것: **오탐 0.** 정상 캡션을 하나라도 버리면 그 그림은 통째로 사라진다.
새 패턴을 넣기 전에 실제 캡션 코퍼스(2026-08-15 기준 15,508건)에 걸어 오탐을 확인할 것.
"""
import pytest

from app.ai.captioning.captioner import _reject_meta


class TestBlocked:
    """이 문구들이 통과하면 점역사가 쓰레기를 받는다."""

    @pytest.mark.parametrize("text", [
        # 2026-08-10 dev 371건에서 실제로 나온 것들
        "이미지가 첨부되지 않았습니다. 파일을 첨부해 주시면 설명해 드리겠습니다.",
        "이미지가 제공되지 않았습니다.",
        "죄송합니다. 이미지를 볼 수 없습니다.",
        "무엇을 도와드릴까요?",
        # 2026-08-15 eval 세션이 넘긴 실제 미검출 응답(자료지침_예2-8, 점자 이미지).
        # 종전 식이 두 군데서 샜다 — 동사가 '판독할'이고 목적어가 '점자 패턴'이었다.
        "이미지의 해상도가 낮아 점자 패턴을 정확히 판독할 수 없습니다. "
        "임의로 점자 내용을 추정하여 옮기지 않겠습니다.",
        # 같은 갈래의 변형
        "글자를 식별할 수 없습니다.",
        "정확하지 않은 내용을 옮기지 않겠습니다.",
    ])
    def test_차단된다(self, text):
        assert _reject_meta(text) == "", f"메타 응답이 캡션으로 나간다: {text[:40]}"


class TestPassed:
    """정상 캡션은 하나도 버리면 안 된다 — 버리면 그 그림이 통째로 사라진다."""

    @pytest.mark.parametrize("text", [
        "그림: 광개토대왕릉비의 모습이다.",
        "만화: 두 학생이 등산하며 대화한다.\n학생1: 힘들다\n학생2: 조금만 더 가자",
        "그래프: 연도별 인구 변화. 2000년 4천만 명, 2020년 5천만 명.",
        # '없'·'제공'이 들어가지만 정상인 캡션 — 종전 실측에서 통과를 확인한 갈래
        "그림: 표지판에 아무 글자도 없다.",
        "도표: 각 기관이 제공하는 서비스를 정리한 표이다.",
        # '해상도가 낮아'는 일부러 패턴에 안 넣었다 — 앞에 실제 묘사가 있는 캡션이 있다
        "그림: 두 개의 초록색 사각형이 겹쳐져 있다. 해상도가 낮아 글자는 흐릿하다.",
    ])
    def test_통과한다(self, text):
        assert _reject_meta(text) == text, f"정상 캡션이 버려진다: {text[:40]}"


def test_빈_입력은_빈_문자열():
    assert _reject_meta("") == ""
    assert _reject_meta(None) == ""
