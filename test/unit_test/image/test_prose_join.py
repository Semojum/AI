"""줄글 설명 안의 이음 — 개조식 나열이 아니라 문장으로 잇는다 (2026-09-09 실물 E2E N2).

증상: `…과정이다., 1 H: 원자핵이 1+이며…, 2 Cl: …` — 마침표 뒤에 쉼표가 오고
캡션 목록 표지가 문장 가운데 남았다. 개조식을 이어 붙인 것이지 줄글이 아니다.

근거: 「점자 자료 제작 지침」 §6.1.4(7) "사실에 대한 설명을 **문장 형식으로 진술**한다.
대부분의 시각 자료 설명에 사용하고, (1)~(4)의 원칙에 따라 표현한다".

⚠ 재료에 없는 말은 만들지 않는다 — 부호를 새로 붙이지 않고, 목록 표지를 뗄 뿐이다.
⚠ 맨 숫자(`1 `)는 §6.6 골격의 **식별 번호**라 안 뗀다(아래 마지막 케이스).
"""
from app.ai.llm.visual_drafts import prose_join


def test_문장으로_끝난_항목은_한_칸_띄어_잇는다():
    got = prose_join(["물이 순환하는 과정이다.", "바다 → 구름.", "구름 → 비."])
    assert got == "물이 순환하는 과정이다. 바다 → 구름. 구름 → 비."
    assert "., " not in got


def test_문장이_아닌_값_나열은_종전대로_쉼표():
    """재료가 문장이 아니면 문장으로 만들 길이 없다 — 부호를 지어내지 않는다."""
    assert prose_join(["막대그래프", "2020년 5,200만", "2021년 5,180만"]) == \
        "막대그래프, 2020년 5,200만, 2021년 5,180만"


def test_캡션_목록_표지는_뗀다():
    assert prose_join(["① 분수", "② 화분에 꽂힌 꽃"]) == "분수, 화분에 꽂힌 꽃"
    assert prose_join(["1. 준비", "2) 실행", "- 정리"]) == "준비, 실행, 정리"


def test_골격_식별_번호는_남긴다():
    """가계도 `1, 2 → 3`(§6.6.4(3)②)·흐름도 분기 `→ 3`(§6.6.2(4)⑥)이 가리킬 대상이다."""
    got = prose_join(["1 정상 남자", "2 정상 여자", "1, 2 → 3 정상 남자"])
    assert got.startswith("1 정상 남자")
    assert "1, 2 → 3 정상 남자" in got


def test_빈_항목은_건너뛴다():
    assert prose_join(["", "  ", "설명"]) == "설명"
    assert prose_join([]) == ""
